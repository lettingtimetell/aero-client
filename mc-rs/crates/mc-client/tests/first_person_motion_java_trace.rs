fn click_at(tick: usize) -> bool {
    tick < 40 && (0..30).any(|k: usize| (k * 20).div_ceil(12) == tick)
}

fn mouse_at(tick: usize) -> f32 {
    if tick < 40 {
        7.5
    } else if tick < 45 {
        50.0
    } else {
        0.0
    }
}

#[test]
fn swing_and_arm_sway_follow_java_frame_by_frame() {
    let world = mc_world::World::new();
    let mut player = PhysicsState::new_player(mc_math::DVec3::new(0.5, 64.0, 0.5));
    let mut hand = FirstPersonRenderState::default();
    let swing_ticks = arm_swing_animation_end(None, None);
    let mut frames = Vec::new();
    let mut accepted = 0;
    for tick in 0..60 {
        // Minecraft.runTick: the queued click, then the entity tick.
        if click_at(tick) && hand.swing_item(swing_ticks) {
            accepted += 1;
        }
        hand.tick_swing(swing_ticks);
        let input = MoveInput {
            yaw: player.yaw,
            pitch: player.pitch,
            ..MoveInput::default()
        };
        mc_physics::tick_player(&world, &mut player, &input);
        for frame in 0..4 {
            let pt = frame as f32 / 4.0;
            // EntityRenderer.updateCameraAndRender: setAngles, then the hand is drawn.
            let mut look = Camera {
                yaw: player.yaw,
                pitch: player.pitch,
                ..Camera::default()
            };
            look.turn_mouse(mouse_at(tick), 0.0);
            player.yaw = look.yaw;
            let arm_yaw = player.prev_render_arm_yaw
                + (player.render_arm_yaw - player.prev_render_arm_yaw) * pt;
            frames.push([hand.swing_amount(pt), player.yaw - arm_yaw]);
        }
    }
    assert_eq!(frames.len(), JAVA_FRAMES.len());
    let mut worst = [0.0_f32; 2];
    for (index, (ours, java)) in frames.iter().zip(JAVA_FRAMES).enumerate() {
        for value in 0..2 {
            let difference = (ours[value] - java[value]).abs();
            worst[value] = worst[value].max(difference);
            assert!(
                difference < 1e-4,
                "tick {} frame {}: {} {} vs Java {}",
                index / 4,
                index % 4,
                ["swing", "sway"][value],
                ours[value],
                java[value]
            );
        }
    }
    eprintln!(
        "{} frames; worst swing difference {}, worst sway difference {} deg; {accepted} of 24 \
         clicks restarted the swing",
        frames.len(),
        worst[0],
        worst[1]
    );
}
