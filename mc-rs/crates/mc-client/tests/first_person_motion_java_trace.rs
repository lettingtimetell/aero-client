//! Bug report: "held items still look slightly too far to the right".
//!
//! In play, the held item's sideways place is the swing pose plus
//! `ItemRenderer.rotateWithPlayerRotations`, a rotation about Y by `(rotationYaw - interpolated
//! renderArmYaw) * 0.1`: a fast turn swings the item sideways. This replays one PvP input timeline
//! through the pieces mc-rs's client uses and compares every frame with the real
//! `EntityPlayerSP`, traced by `crates/mc-client/javaref/HeldMotionTraceRef.java`
//! (`generate-held-motion-trace.ps1`):
//!
//! * 60 ticks of 4 frames; clicks at 12 CPS for the first 40 ticks (each processed at the next
//!   tick boundary), a 90 deg/s turn for 40 ticks, a 600 deg/s flick for 5, then still;
//! * swing: `FirstPersonRenderState::swing_item` (Java's half-animation restart guard) per click,
//!   `tick_swing` per tick, `swing_amount(pt)` per frame;
//! * sway: `Camera::turn_mouse` per frame (`Entity.setAngles`), `mc_physics::tick_player` per
//!   tick (`EntityPlayerSP.updateEntityActionState`'s 0.5 easing), and the yaw minus the
//!   interpolated `renderArmYaw` per frame, exactly what `first_person_view_rotation` turns by a
//!   tenth.
//!
//! Java's numbers are float; mc-rs reproduces the same float and double steps, so the frames are
//! compared to 1e-4.

