//! "Getting stuck in a solid block shouldn't show you anything
//! in the real game, but it does right now. I believe usually its just a screen of the dark dirt
//! texture".
//!
//! The reference is vanilla's own renderer. `crates/mc-client/javaref/SuffocationRef.java`
//! (`generate-suffocation.ps1`) calls the real private `EntityRenderer.renderHand` at 1920x1080
//! with the eye inside a block, after putting the GL state where `renderWorldPass` leaves it. When
//! `ItemRenderer.renderBlockInHand` draws, it measured, for the empty hand and for held items
//! alike: **blend off**, alpha test off, depth test on with `GL_LEQUAL`, depth writes on, colour
//! (0.1, 0.1, 0.1, 0.5). The quad is `(-1..1, -1..1)` at eye depth 0.5 through the 70-degree hand
//! projection, so only the middle of the sprite is on screen, in texels about 193 px square.
//!
//! The tables below are that run's output:
//! * [`NO_HAND`]: `hideGUI`, so `renderItemInFirstPerson` is skipped while `renderOverlays` still
//!   runs. The texel grid as the x positions along the middle row and the y positions along the
//!   middle column where the colour changes, and the colour of every cell.
//! * [`HAND`]: the pixels that differ from the matching no-hand render: the parts of the held item
//!   vanilla leaves visible in front of the quad, because they are nearer than 0.5.
//!
//! mc-rs renders each case through the real `FirstPersonPhase` and `OverlayPhase`, wired exactly
//! as the frame driver wires them (`clear_depth_for_overlay`, `opaque_block_hand_depth`), on a
//! magenta clear: any blending would let magenta through.
//!
//! Skips (loudly) without the vanilla jar (set `MC_JARS_DIR`) or a wgpu adapter. Set
//! `MC_SUFFOCATION_DUMP=<dir>` to also write each mc-rs render as a PNG.

