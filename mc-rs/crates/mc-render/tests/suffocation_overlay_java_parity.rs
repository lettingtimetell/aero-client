fn jars_dir() -> Option<PathBuf> {
    if let Some(dir) = std::env::var_os("MC_JARS_DIR") {
        let dir = PathBuf::from(dir);
        return dir.is_dir().then_some(dir);
    }
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).ancestors().nth(3)?;
    let dir = root.join("MCP-919-main").join("jars");
    dir.is_dir().then_some(dir)
}

fn vanilla_jar() -> Option<PathBuf> {
    let jar = jars_dir()?.join("versions").join("1.8.9").join("1.8.9.jar");
    jar.is_file().then_some(jar)
}

fn resources() -> Option<ResourceManager> {
    let mut rm = ResourceManager::new();
    rm.push_pack(Box::new(ZipResourcePack::open(&vanilla_jar()?).ok()?));
    Some(rm)
}

/// Bake and install the vanilla jar's models and atlas once for this test process.
fn baked_atlas() -> Option<Atlas> {
    use std::sync::OnceLock;
    static ATLAS: OnceLock<Option<Atlas>> = OnceLock::new();
    ATLAS
        .get_or_init(|| {
            let rm = resources()?;
            let (baked, _report) =
                mc_assets::bake_all(&rm, 4096).expect("bake_all against the real jar");
            let atlas = baked.atlas.clone();
            mc_assets::install(baked);
            Some(atlas)
        })
        .clone()
}

/// `renderHand`'s camera: 1920x1080, the fixed 70-degree hand FOV, Java's far plane 2 x 128.
fn hand_camera() -> Camera {
    let mut camera = Camera::default();
    camera.set_viewport(W, H);
    camera.far = 128.0;
    camera.update();
    camera
}

const BOW_MAX_USE: i32 = 72_000;
const APPLE_MAX_USE: i32 = 32;

/// Render one case: the first-person phase (hand or not) then the overlay phase, as the driver
/// wires them while the eye is inside a block.
fn render(
    gpu: &mut Gpu,
    atlas: &Atlas,
    rm: &ResourceManager,
    sprite: &str,
    hand: Option<&HandRef>,
) -> Vec<u8> {
    let mut first_person = FirstPersonPhase::new(gpu);
    first_person.set_atlas(gpu, atlas);
    assert!(
        first_person.load_skin_texture(gpu, rm, "textures/entity/steve.png"),
        "the jar's Steve skin"
    );
    first_person.render_state.prev_equipped_progress = 1.0;
    first_person.render_state.equipped_progress = 1.0;
    first_person.partial_ticks = 0.0;
    first_person.combined_light = mc_render::entity::render::FULL_BRIGHT_COMBINED_LIGHT;
    first_person.clear_depth_for_overlay = true;
    match hand {
        // hideGUI: renderItemInFirstPerson is skipped, renderOverlays is not.
        None => first_person.render_state.visibility.hide_gui = true,
        Some(case) => {
            if let Some(item) = case.item {
                let id = mc_data::item_by_name(item).expect("a real 1.8.9 item");
                let (model, action, max_use) = match (item, case.use_count) {
                    // 20 ticks drawn: bow_pulling_2, Java's variant 3.
                    ("bow", count) if count > 0 => (
                        mc_assets::item_model_for_variant(id, 3).clone(),
                        FirstPersonUseAction::Bow,
                        BOW_MAX_USE,
                    ),
                    ("apple", count) if count > 0 => (
                        mc_assets::item_model_for(id).clone(),
                        FirstPersonUseAction::EatDrink,
                        APPLE_MAX_USE,
                    ),
                    _ => (
                        mc_assets::item_model_for(id).clone(),
                        FirstPersonUseAction::Idle,
                        32,
                    ),
                };
                let gui_3d = model.gui_3d;
                first_person.set_item_model(Some(model), gui_3d);
                first_person.render_state.use_action = action;
                first_person.render_state.item_use_count = case.use_count;
                first_person.render_state.max_item_use_duration = max_use;
            }
        }
    }

    let mut overlay = OverlayPhase::new(gpu);
    overlay.set_block_atlas(gpu, atlas);
    overlay.set_opaque_block_uv(Some(
        mc_assets::model::sprite(&ResourceLocation::minecraft(sprite)).uv,
    ));
    overlay.opaque_block_hand_depth = true;

    let camera = hand_camera();
    let mut phases = PhaseList::new();
    phases.clear_color = wgpu::Color {
        r: 1.0,
        g: 0.0,
        b: 1.0,
        a: 1.0,
    };
    phases.insert(PhaseOrder::FIRST_PERSON, Box::new(first_person));
    phases.insert(PhaseOrder::POST, Box::new(overlay));
    let frame = gpu.acquire().expect("acquire offscreen frame");
    phases.render(gpu, frame.view(), &camera, 0.0);
    gpu.read_pixels().expect("readback")
}

fn rgb(pixels: &[u8], x: u32, y: u32) -> [u8; 3] {
    let i = ((y * W + x) * 4) as usize;
    [pixels[i], pixels[i + 1], pixels[i + 2]]
}

fn edges(pixels: &[u8], horizontal: bool) -> Vec<u32> {
    if horizontal {
        (1..W)
            .filter(|&x| rgb(pixels, x, 540) != rgb(pixels, x - 1, 540))
            .collect()
    } else {
        (1..H)
            .filter(|&y| rgb(pixels, 960, y) != rgb(pixels, 960, y - 1))
            .collect()
    }
}

fn diff_mask(pixels: &[u8], baseline: &[u8]) -> Mask {
    let mut mask = Mask {
        count: 0,
        min_x: i64::from(W),
        max_x: -1,
        min_y: i64::from(H),
        max_y: -1,
        cx: 0.0,
        cy: 0.0,
    };
    for y in 0..H {
        for x in 0..W {
            if rgb(pixels, x, y) == rgb(baseline, x, y) {
                continue;
            }
            mask.count += 1;
            mask.cx += f64::from(x) + 0.5;
            mask.cy += f64::from(y) + 0.5;
            mask.min_x = mask.min_x.min(i64::from(x));
            mask.max_x = mask.max_x.max(i64::from(x));
            mask.min_y = mask.min_y.min(i64::from(y));
            mask.max_y = mask.max_y.max(i64::from(y));
        }
    }
    if mask.count > 0 {
        mask.cx /= mask.count as f64;
        mask.cy /= mask.count as f64;
    }
    mask
}

fn headless() -> Option<Gpu> {
    match Gpu::headless(
        W,
        H,
        GpuOptions {
            vsync: false,
            sample_count: 1,
            low_power: false,
        },
    ) {
        Ok(gpu) => Some(gpu),
        Err(RenderError::NoAdapter) => {
            eprintln!("SKIP: no wgpu adapter available on this machine");
            None
        }
        Err(error) => panic!("headless context creation failed: {error}"),
    }
}

fn dump(name: &str, pixels: &[u8]) {
    if let Some(dir) = std::env::var_os("MC_SUFFOCATION_DUMP").map(PathBuf::from) {
        std::fs::create_dir_all(&dir).expect("dump dir");
        image::RgbaImage::from_raw(W, H, pixels.to_vec())
            .expect("rgba frame")
            .save(dir.join(format!("{name}.png")))
            .expect("write png");
    }
}

/// The quad alone: opaque, and the same texels in the same cells as vanilla's.
#[test]
fn suffocation_quad_covers_the_screen_like_java() {
    let (Some(atlas), Some(rm)) = (baked_atlas(), resources()) else {
        eprintln!("SKIP: no vanilla jar; set MC_JARS_DIR");
        return;
    };
    let Some(mut gpu) = headless() else { return };
    let mut failures = Vec::new();
    for case in NO_HAND {
        let pixels = render(&mut gpu, &atlas, &rm, case.sprite, None);
        dump(case.name, &pixels);

        // Opaque: nothing of the magenta clear may survive, and every pixel is a dark texel.
        let brightest = pixels
            .chunks_exact(4)
            .map(|p| p[0].max(p[1]).max(p[2]))
            .max()
            .unwrap_or(255);
        if brightest > 26 {
            failures.push(format!(
                "{}: brightest channel {brightest}; the quad is 0.1 x texel and opaque, so no \
                 channel may exceed 26 (the clear colour shows through)",
                case.name
            ));
        }

        let xs = edges(&pixels, true);
        let ys = edges(&pixels, false);
        let close = |ours: &[u32], java: &[u32]| {
            ours.len() == java.len() && ours.iter().zip(java).all(|(a, b)| a.abs_diff(*b) <= 1)
        };
        eprintln!(
            "{:14} x edges java {:?} mc-rs {:?}; y edges java {:?} mc-rs {:?}",
            case.name, case.x_edges, xs, case.y_edges, ys
        );
        if !close(&xs, case.x_edges) || !close(&ys, case.y_edges) {
            failures.push(format!(
                "{}: texel edges x {xs:?} y {ys:?}, Java x {:?} y {:?}",
                case.name, case.x_edges, case.y_edges
            ));
            continue;
        }

        // Each cell's colour at its centre, using Java's edges.
        let bounds = |edges: &[u32], end: u32| {
            let mut b = vec![0];
            b.extend_from_slice(edges);
            b.push(end);
            b
        };
        let bx = bounds(case.x_edges, W);
        let by = bounds(case.y_edges, H);
        let mut worst = 0u8;
        for (row, pair_y) in by.windows(2).enumerate() {
            for (column, pair_x) in bx.windows(2).enumerate() {
                let java = case.cells[row * (bx.len() - 1) + column];
                let java = [(java >> 16) as u8, (java >> 8) as u8, java as u8];
                let ours = rgb(
                    &pixels,
                    (pair_x[0] + pair_x[1]) / 2,
                    (pair_y[0] + pair_y[1]) / 2,
                );
                for channel in 0..3 {
                    worst = worst.max(ours[channel].abs_diff(java[channel]));
                }
            }
        }
        eprintln!("{:14} worst cell channel difference {worst}", case.name);
        if worst > 1 {
            failures.push(format!(
                "{}: a cell colour differs from Java's by {worst}",
                case.name
            ));
        }
    }
    assert!(
        failures.is_empty(),
        "the suffocation overlay does not look like vanilla 1.8.9's: {failures:#?}"
    );
}

/// The quad over the hand: only the parts of the held item nearer than eye depth 0.5 survive
/// Java's GL_LEQUAL test, exactly as vanilla shows them.
#[test]
fn suffocation_quad_hides_the_hand_like_java() {
    let (Some(atlas), Some(rm)) = (baked_atlas(), resources()) else {
        eprintln!("SKIP: no vanilla jar; set MC_JARS_DIR");
        return;
    };
    let Some(mut gpu) = headless() else { return };
    let baselines: Vec<(&str, Vec<u8>)> = NO_HAND
        .iter()
        .map(|case| (case.name, render(&mut gpu, &atlas, &rm, case.sprite, None)))
        .collect();
    let mut failures = Vec::new();
    for case in HAND {
        let base = NO_HAND
            .iter()
            .position(|no_hand| no_hand.name == case.baseline)
            .expect("a baseline");
        let pixels = render(&mut gpu, &atlas, &rm, NO_HAND[base].sprite, Some(case));
        dump(case.name, &pixels);
        let ours = diff_mask(&pixels, &baselines[base].1);
        let java = case.visible;
        eprintln!(
            "{:20} visible java: n {:6} x {:4}..{:4} y {:4}..{:4} c ({:7.2}, {:7.2})   mc-rs: n \
             {:6} x {:4}..{:4} y {:4}..{:4} c ({:7.2}, {:7.2})",
            case.name,
            java.count,
            java.min_x,
            java.max_x,
            java.min_y,
            java.max_y,
            java.cx,
            java.cy,
            ours.count,
            ours.min_x,
            ours.max_x,
            ours.min_y,
            ours.max_y,
            ours.cx,
            ours.cy,
        );
        let ok = if java.count == 0 {
            ours.count == 0
        } else {
            let tolerance = (java.count as f64 * 0.02).max(50.0);
            let count_close = (ours.count as f64 - java.count as f64).abs() <= tolerance;
            let edges_close = (ours.min_x - java.min_x).abs() <= 2
                && (ours.max_x - java.max_x).abs() <= 2
                && (ours.min_y - java.min_y).abs() <= 2
                && (ours.max_y - java.max_y).abs() <= 2;
            let centroid_close =
                (ours.cx - java.cx).abs() <= 1.5 && (ours.cy - java.cy).abs() <= 1.5;
            count_close && edges_close && centroid_close
        };
        if !ok {
            failures.push(format!("{}: java {java:?} vs mc-rs {ours:?}", case.name));
        }
    }
    assert!(
        failures.is_empty(),
        "the parts of the hand left in front of the suffocation overlay differ from vanilla \
         1.8.9's: {failures:#?}"
    );
}
