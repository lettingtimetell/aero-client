// BORDER_OUTSIDE: prevVignetteBrightness after the call = 0.0

const GREY: [f64; 3] = [0.5, 0.5, 0.5];
const WARM: [f64; 3] = [0.9, 0.6, 0.3];

/// `(name, Java table, background, light level, previous brightness, border warning colour as
/// the client computes it: `(0, f, f, 1)` with `f = 1 - distance / warningDistance`)`.
type Case = (
    &'static str,
    &'static [[u8; 3]; 144],
    [f64; 3],
    f32,
    f32,
    Option<[f32; 4]>,
);

const CASES: [Case; 5] = [
    ("DARK", &DARK, GREY, 0.0, 1.0, None),
    ("HALF", &HALF, WARM, 0.5, 0.5, None),
    ("DIM", &DIM, GREY, 0.8, 0.2, None),
    (
        "BORDER_INSIDE",
        &BORDER_INSIDE,
        WARM,
        1.0,
        0.0,
        Some([0.0, 0.6, 0.6, 1.0]),
    ),
    (
        "BORDER_OUTSIDE",
        &BORDER_OUTSIDE,
        WARM,
        1.0,
        0.0,
        Some([0.0, 1.4, 1.4, 1.0]),
    ),
];

#[test]
fn the_vignette_matches_java_render_vignette_pixel_for_pixel() {
    let Some(rm) = vanilla_resources() else {
        eprintln!("SKIP: the vanilla jar is not available");
        return;
    };
    let Some(mut gpu) = headless() else {
        return;
    };
    for (name, java, background, light, prev, border) in CASES {
        let mut overlay = OverlayPhase::new(&gpu);
        overlay.load_vignette_texture(&gpu, &rm);
        assert!(
            overlay.has_vignette_texture(),
            "vignette.png loads from the jar"
        );
        // java: renderVignette eases `prevVignetteBrightness` once, then draws.
        overlay.prev_vignette_brightness = prev;
        overlay.set_vignette_brightness(Some(light));
        overlay.set_border_warning(border);
        let mut phases = PhaseList::new();
        phases.clear_color = wgpu::Color {
            r: background[0],
            g: background[1],
            b: background[2],
            a: 1.0,
        };
        phases.insert(PhaseOrder::POST, Box::new(overlay));
        let mut camera = Camera::default();
        camera.set_viewport(W, H);
        camera.update();
        let frame = gpu.acquire().expect("acquire");
        phases.render(&gpu, frame.view(), &camera, 0.0);
        frame.present(&gpu.queue);
        let pixels = gpu.read_pixels().expect("readback");
        let mut worst = 0;
        for gy in 0..GRID_Y {
            for gx in 0..GRID_X {
                let x = gx * (W / GRID_X) + W / GRID_X / 2;
                let y = gy * (H / GRID_Y) + H / GRID_Y / 2;
                let i = ((y * W + x) * 4) as usize;
                let got = [pixels[i], pixels[i + 1], pixels[i + 2]];
                let want = java[(gy * GRID_X + gx) as usize];
                for c in 0..3 {
                    let diff = got[c].abs_diff(want[c]);
                    worst = worst.max(diff);
                    assert!(
                        diff <= 1,
                        "{name} at ({x}, {y}) channel {c}: mc-rs {got:?}, Java {want:?}"
                    );
                }
            }
        }
        eprintln!("{name}: 144 points within {worst}/255 of Java");
    }
}
