//! Item 8 ("border vignette looks completely wrong"):
//! `OverlayPhase`'s vignette against the real `GuiIngame.renderVignette`.
//!
//! The tables are the Java renderer's own pixels: `crates/mc-client/javaref/VignetteRef.java`
//! (run by `generate-vignette.ps1`) calls the recompiled 1.8.9 `renderVignette` in an LWJGL
//! Pbuffer at 1920x1080, GUI scale 2, over a cleared framebuffer, and prints the colour at a
//! 16x9 grid of pixel centres. This test draws the same cases with the real `vignette.png` and
//! compares every point within 1/255 (bilinear filtering hardware rounding).
//!
//! `BORDER_OUTSIDE` is the bug this pins: two blocks outside the border Java's strength
//! `1 - distance / warningDistance` is 1.4, and fixed-function GL clamps `GlStateManager.color`
//! to 1 before the texture modulate. mc-rs used to multiply the texel by 1.4, so the red warning
//! outside a border was far stronger than vanilla's (the blend then saturated at the screen's
//! edges).

