/// GPU and GL may round the last bit differently.
const TOLERANCE: u8 = 2;

/// Where each reference lightmap colour lives in the test lightmap: (colour, sky, block).
const LIGHTMAP_SLOTS: [([u8; 3], u8, u8); 3] = [
    ([255, 255, 255], 15, 15),
    ([77, 77, 77], 0, 0),
    ([150, 120, 90], 5, 10),
];

/// java: `getBrightnessForRender`'s packing, `sky << 20 | block << 4`.
fn packed_light(colour: [u8; 3]) -> u32 {
    let (_, sky, block) = LIGHTMAP_SLOTS
        .iter()
        .find(|(slot, _, _)| *slot == colour)
        .expect("a reference lightmap colour");
    ((u32::from(*sky) * 16) << 16) | (u32::from(*block) * 16)
}

fn test_lightmap() -> Lightmap {
    // Every other texel is magenta, so a mis-addressed sample cannot pass for a reference value.
    let mut rgba = [255u8, 0, 255, 255].repeat(256);
    for (colour, sky, block) in LIGHTMAP_SLOTS {
        let i = (usize::from(sky) << 4 | usize::from(block)) * 4;
        rgba[i..i + 3].copy_from_slice(&colour);
    }
    Lightmap { rgba }
}

fn within(a: [u8; 3], b: [u8; 3]) -> bool {
    a.iter().zip(&b).all(|(x, y)| x.abs_diff(*y) <= TOLERANCE)
}

/// The GL measurements are `min(255, body + lightmap)` whatever `f2` is, and the old
/// `SrcAlpha, OneMinusSrc` blend (`f2 * white`) matches none of the visible cases: this is what
/// makes the GPU comparison below a real test rather than a tautology.
#[test]
fn the_gl_flash_adds_the_lightmap_to_the_body_and_ignores_the_colour_alpha() {
    let mut old_matches = Vec::new();
    for r in FLASH_REFS {
        let additive: [u8; 3] = core::array::from_fn(|i| r.body[i].saturating_add(r.lightmap[i]));
        assert!(
            within(additive, r.rgb),
            "body {:?} lightmap {:?} f2 {}: GL {:?}, body + lightmap {:?}",
            r.body,
            r.lightmap,
            r.alpha,
            r.rgb,
            additive
        );
        assert_eq!(r.dst_alpha, 255, "the framebuffer keeps the body's alpha");
        // The pre-fix mc-rs result: `f2 * white + body * (1 - white)`.
        let grey = (r.alpha * 255.0).round() as u8;
        if within([grey; 3], r.rgb) {
            old_matches.push((r.body, r.lightmap, r.alpha));
        }
    }
    // Only one coincidence: grey 204 (f2 0.8) against 128 + 77 = 205 on a grey body at night.
    assert_eq!(
        old_matches,
        vec![([128, 128, 128], [77, 77, 77], 0.8)],
        "the old grey flash matches GL only by coincidence"
    );
    // Daylight: the flash is pure white on every body.
    assert!(FLASH_REFS
        .iter()
        .filter(|r| r.lightmap == [255; 3])
        .all(|r| r.rgb == [255; 3]));
}

const SIZE: u32 = 192;
/// Cells per row and column of the test frame; every case gets one cell.
const GRID: u32 = 6;
/// Camera-relative depth of every test quad.
const DEPTH: f32 = 3.0;

fn headless() -> Option<Gpu> {
    match Gpu::headless(
        SIZE,
        SIZE,
        GpuOptions {
            vsync: false,
            sample_count: 1,
            low_power: false,
        },
    ) {
        Ok(g) => Some(g),
        Err(RenderError::NoAdapter) => {
            eprintln!("SKIP: no wgpu adapter on this machine");
            None
        }
        Err(e) => panic!("headless context creation failed: {e}"),
    }
}

fn camera() -> Camera {
    let mut cam = Camera::default();
    cam.set_viewport(SIZE, SIZE);
    cam.update();
    cam
}

/// Centre of cell `index` at [`DEPTH`], well inside the default 70-degree frustum.
fn cell_centre(index: usize) -> Vec3 {
    let pitch = 3.6 / GRID as f32;
    let col = (index as u32 % GRID) as f32;
    let row = (index as u32 / GRID) as f32;
    Vec3::new(
        -1.8 + (col + 0.5) * pitch,
        -1.8 + (row + 0.5) * pitch,
        DEPTH,
    )
}

/// The framebuffer pixel a camera-relative point lands on.
fn pixel_of(cam: &Camera, point: Vec3) -> (u32, u32) {
    let clip = cam.view_proj() * Vec4::new(point.x, point.y, point.z, 1.0);
    let ndc = clip.truncate() / clip.w;
    let x = ((ndc.x * 0.5 + 0.5) * SIZE as f32) as u32;
    let y = ((0.5 - ndc.y * 0.5) * SIZE as f32) as u32;
    assert!(x < SIZE && y < SIZE, "cell centre {point:?} is off screen");
    (x, y)
}

/// A camera-facing square. The up normal makes the standard item light clamp to 1, so an
/// `Opaque` body under a white lightmap is exactly its texel.
fn square(centre: Vec3, color: [f32; 4]) -> Vec<EntityVertex> {
    let half = 0.12;
    let v = |dx: f32, dy: f32| EntityVertex {
        pos: [centre.x + dx, centre.y + dy, centre.z],
        uv: [0.5, 0.5],
        normal: [0.0, 1.0, 0.0],
        color,
    };
    vec![
        v(-half, -half),
        v(half, -half),
        v(half, half),
        v(-half, -half),
        v(half, half),
        v(-half, half),
    ]
}

fn texel_key(texel: [u8; 3]) -> String {
    format!("x6-tnt/{}-{}-{}", texel[0], texel[1], texel[2])
}

/// The production `Opaque` body followed by the production `TntFlash` replay (vertex colour
/// [`TNT_FLASH_COLOR`], the entity's packed light), against every GL case.
#[test]
fn tnt_flash_pipeline_matches_fixed_function_gl_pixel_for_pixel() {
    let Some(mut gpu) = headless() else {
        return;
    };
    let cam = camera();
    let mut phase = EntityPhase::new(&gpu);
    let mut bodies: Vec<[u8; 3]> = FLASH_REFS.iter().map(|r| r.body).collect();
    bodies.sort_unstable();
    bodies.dedup();
    for body in &bodies {
        phase.upload_texture(
            &gpu,
            &texel_key(*body),
            &[body[0], body[1], body[2], 255],
            1,
            1,
        );
    }
    phase.set_lightmap(&gpu, &test_lightmap());
    phase.begin();

    let mut expected = Vec::new();
    for (index, r) in FLASH_REFS.iter().enumerate() {
        let centre = cell_centre(index);
        // The body: drawn under the white slot so the destination is exactly the body colour.
        phase.push_blended_lit(
            &texel_key(r.body),
            LayerBlend::Opaque,
            packed_light([255; 3]),
            &square(centre, [1.0; 4]),
        );
        // The flash replays the same geometry under the entity's light.
        phase.push_blended_lit(
            EntityPhase::SOLID_TEXTURE,
            LayerBlend::TntFlash,
            packed_light(r.lightmap),
            &square(centre, TNT_FLASH_COLOR),
        );
        expected.push((
            format!("body {:?} lightmap {:?} f2 {}", r.body, r.lightmap, r.alpha),
            centre,
            r.rgb,
        ));
    }
    assert!(expected.len() <= (GRID * GRID) as usize);
    phase.finish(&gpu);

    let mut list = PhaseList::new();
    list.clear_color = wgpu::Color::BLACK;
    list.insert(PhaseOrder::ENTITIES, Box::new(phase));
    let frame = gpu.acquire().expect("acquire offscreen frame");
    list.render(&gpu, frame.view(), &cam, 0.0);
    frame.present(&gpu.queue);
    let pixels = gpu.read_pixels().expect("read back the frame");

    let mut mismatches = Vec::new();
    for (label, centre, gl) in &expected {
        let (x, y) = pixel_of(&cam, *centre);
        let i = ((y * SIZE + x) * 4) as usize;
        let got = [pixels[i], pixels[i + 1], pixels[i + 2]];
        if !within(got, *gl) {
            mismatches.push(format!("{label}: wgpu {got:?}, GL {gl:?}"));
        }
    }
    assert!(
        mismatches.is_empty(),
        "{} of {} cells differ from fixed-function GL by more than {TOLERANCE}:\n{}",
        mismatches.len(),
        expected.len(),
        mismatches.join("\n")
    );
}
