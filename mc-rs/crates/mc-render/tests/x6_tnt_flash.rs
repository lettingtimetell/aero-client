//! "TNT blinks are grey instead of white".
//!
//! The table below comes from `crates/mc-client/javaref/TntFlashRef.java` (regenerate with
//! `generate-tnt-flash.ps1`). It replays `RenderTNTPrimed.doRender`'s flash pass call for call in
//! an LWJGL 2 Pbuffer with 8-bit destination alpha: the lightmap on texture unit 1 exactly as
//! `EntityRenderer.enableLightmap` sets it, then `disableTexture2D`, `disableLighting`,
//! `blendFunc(770, 772)`, `color(1, 1, 1, f2)`, polygon offset, and one
//! `DefaultVertexFormats.ITEM` quad through the real `Tessellator` followed by
//! `putColorRGB_F4(1, 1, 1)` (what `BlockModelRenderer.renderModelBrightnessColorQuads` does), over
//! a destination that holds the opaque body (alpha 255).
//!
//! What it shows:
//!
//! * `f2` is dead: the ITEM format's per-vertex colour (alpha 255) replaces `GlStateManager.color`,
//!   so alpha 0, 0.4 and 0.8 give identical pixels;
//! * `GL_SRC_ALPHA, GL_DST_ALPHA` adds the flash to the body, and the flash is the lightmap texel
//!   (texture unit 0 is off, unit 1 is not): `min(255, body + lightmap)`, i.e. white by day.
//!
//! mc-rs used `SrcAlpha, OneMinusSrc` with alpha `f2`: `f2 * white + body * 0`, a grey of at most
//! 204/255. The GPU test draws the production `TntFlash` pipeline over a body drawn by the
//! production `Opaque` pipeline and compares every case. It skips cleanly (printing `SKIP:`)
//! without an adapter.

