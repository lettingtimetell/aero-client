/// Largest per-channel difference accepted between a computed or wgpu value and the GL frame:
/// everything ends in an 8-bit target, and GL's fixed-function stages round differently from
/// f32 maths.
const TOLERANCE: u8 = 2;

/// The reference's three lightmap colours, each in its own texel of one 16x16 lightmap, as
/// `(colour, sky, block)`. A batch selects one with Java's packed coordinate.
const LIGHTMAP_SLOTS: [([u8; 3], u8, u8); 3] = [
    ([255, 255, 255], 15, 15),
    ([77, 77, 77], 0, 0),
    ([150, 120, 90], 5, 10),
];

/// java: `getBrightnessForRender`'s packing, `sky << 20 | block << 4`.
fn packed_light(colour: [u8; 3]) -> u32 {
    let (_, sky, block) = LIGHTMAP_SLOTS
        .iter()
        .find(|(slot, _, _)| *slot == colour)
        .expect("a reference lightmap colour");
    ((u32::from(*sky) * 16) << 16) | (u32::from(*block) * 16)
}

fn test_lightmap() -> Lightmap {
    // Every other texel is magenta, so a mis-addressed sample cannot pass for a reference value.
    let mut rgba = [255u8, 0, 255, 255].repeat(256);
    for (colour, sky, block) in LIGHTMAP_SLOTS {
        let i = (usize::from(sky) << 4 | usize::from(block)) * 4;
        rgba[i..i + 3].copy_from_slice(&colour);
    }
    Lightmap { rgba }
}

/// `RenderHelper.enableStandardItemLighting`: scene ambient 0.4 plus 0.6 per light.
fn standard_item_light(normal: Vec3) -> f32 {
    let light0 = Vec3::new(0.2, 1.0, -0.7).normalize();
    let light1 = Vec3::new(-0.2, 1.0, 0.7).normalize();
    let n = normal.normalize();
    0.4 + 0.6 * n.dot(light0).max(0.0) + 0.6 * n.dot(light1).max(0.0)
}

fn unit(channel: u8) -> f32 {
    f32::from(channel) / 255.0
}

/// GL's order: the lit primary colour clamped, then the texel stage, then the lightmap stage.
fn clamp_then_lightmap(r: &LitRef) -> [f32; 3] {
    let light = standard_item_light(Vec3::from(r.normal));
    core::array::from_fn(|i| {
        (r.tint[i] * light).clamp(0.0, 1.0) * unit(r.texel[i]) * unit(r.lightmap[i])
    })
}

/// The old shader's order: the lightmap inside the clamp.
fn lightmap_inside_clamp(r: &LitRef) -> [f32; 3] {
    let light = standard_item_light(Vec3::from(r.normal));
    core::array::from_fn(|i| {
        (r.tint[i] * light * unit(r.lightmap[i])).clamp(0.0, 1.0) * unit(r.texel[i])
    })
}

/// `GL_SRC_COLOR, GL_ONE` over black: `src * src`, with the lightmap stage in `src`.
fn glint_with_lightmap(r: &GlintRef) -> [f32; 3] {
    core::array::from_fn(|i| {
        let src = unit(r.texel[i]) * r.color[i] * unit(r.lightmap[i]);
        src * src
    })
}

/// The old foil: no lightmap stage.
fn glint_without_lightmap(r: &GlintRef) -> [f32; 3] {
    core::array::from_fn(|i| {
        let src = unit(r.texel[i]) * r.color[i];
        src * src
    })
}

fn to_u8(colour: [f32; 3]) -> [u8; 3] {
    colour.map(|c| (c.clamp(0.0, 1.0) * 255.0).round() as u8)
}

fn within(a: [u8; 3], b: [u8; 3]) -> bool {
    a.iter().zip(&b).all(|(x, y)| x.abs_diff(*y) <= TOLERANCE)
}

/// The GL measurements are the fixed-function order, and they tell the old order apart: this is
/// what makes the GPU comparison below a real test rather than a tautology.
#[test]
fn the_gl_reference_is_clamp_then_texel_then_lightmap() {
    let mut old_differs = 0;
    for r in LIT_REFS {
        let vanilla = to_u8(clamp_then_lightmap(r));
        assert!(
            within(vanilla, r.rgb),
            "normal {:?} tint {:?} lightmap {:?} texel {:?}: GL {:?}, clamp-then-lightmap {:?}",
            r.normal,
            r.tint,
            r.lightmap,
            r.texel,
            r.rgb,
            vanilla
        );
        let old = to_u8(lightmap_inside_clamp(r));
        if !within(old, r.rgb) {
            old_differs += 1;
        }
    }
    // Upward faces (light 1.37) under the two dark lightmaps: up to 37% brighter.
    let up_night = LIT_REFS
        .iter()
        .find(|r| {
            r.normal == [0.0, 1.0, 0.0]
                && r.tint == [1.0; 3]
                && r.texel == [255; 3]
                && r.lightmap == [77; 3]
        })
        .expect("the up-facing night case");
    assert_eq!(up_night.rgb, [77; 3], "GL: clamp(1.37) * 77/255");
    assert_eq!(
        to_u8(lightmap_inside_clamp(up_night)),
        [106; 3],
        "old: clamp(1.37 * 77/255)"
    );
    // The faces whose lit colour exceeds 1 (up, and up-tilted with a bright tint) under the two
    // dark lightmaps.
    assert_eq!(
        old_differs, 16,
        "the cases that tell the lightmap-inside-clamp order apart"
    );

    let mut old_glint_differs = 0;
    for r in GLINT_REFS {
        let vanilla = to_u8(glint_with_lightmap(r));
        assert!(
            within(vanilla, r.rgb),
            "foil {:?} lightmap {:?} texel {:?}: GL {:?}, with lightmap {:?}",
            r.color,
            r.lightmap,
            r.texel,
            r.rgb,
            vanilla
        );
        if !within(to_u8(glint_without_lightmap(r)), r.rgb) {
            old_glint_differs += 1;
        }
    }
    // Every case under a dark lightmap: 8 of the 12.
    assert_eq!(
        old_glint_differs, 8,
        "the foil cases that need the lightmap stage"
    );
}

const SIZE: u32 = 352;
/// Cells per row and column of the test frame; every case gets one cell.
const GRID: u32 = 11;
/// Camera-relative depth of every test quad.
const DEPTH: f32 = 3.0;

fn headless() -> Option<Gpu> {
    match Gpu::headless(
        SIZE,
        SIZE,
        GpuOptions {
            vsync: false,
            sample_count: 1,
            low_power: false,
        },
    ) {
        Ok(g) => Some(g),
        Err(RenderError::NoAdapter) => {
            eprintln!("SKIP: no wgpu adapter on this machine");
            None
        }
        Err(e) => panic!("headless context creation failed: {e}"),
    }
}

fn camera() -> Camera {
    let mut cam = Camera::default();
    cam.set_viewport(SIZE, SIZE);
    cam.update();
    cam
}

/// Centre of cell `index` at [`DEPTH`], well inside the default 70-degree frustum.
fn cell_centre(index: usize) -> Vec3 {
    let pitch = 3.6 / GRID as f32;
    let col = (index as u32 % GRID) as f32;
    let row = (index as u32 / GRID) as f32;
    Vec3::new(
        -1.8 + (col + 0.5) * pitch,
        -1.8 + (row + 0.5) * pitch,
        DEPTH,
    )
}

/// The framebuffer pixel a camera-relative point lands on.
fn pixel_of(cam: &Camera, point: Vec3) -> (u32, u32) {
    let clip = cam.view_proj() * Vec4::new(point.x, point.y, point.z, 1.0);
    let ndc = clip.truncate() / clip.w;
    let x = ((ndc.x * 0.5 + 0.5) * SIZE as f32) as u32;
    let y = ((0.5 - ndc.y * 0.5) * SIZE as f32) as u32;
    assert!(x < SIZE && y < SIZE, "cell centre {point:?} is off screen");
    (x, y)
}

/// A camera-facing square carrying an arbitrary (world-space) normal: the shader lights by the
/// normal, not by the geometry.
fn square(centre: Vec3, normal: [f32; 3], tint: [f32; 3]) -> Vec<EntityVertex> {
    let half = 0.09;
    let v = |dx: f32, dy: f32| EntityVertex {
        pos: [centre.x + dx, centre.y + dy, centre.z],
        uv: [0.5, 0.5],
        normal,
        color: [tint[0], tint[1], tint[2], 1.0],
    };
    vec![
        v(-half, -half),
        v(half, -half),
        v(half, half),
        v(-half, -half),
        v(half, half),
        v(-half, half),
    ]
}

fn texel_key(texel: [u8; 3]) -> String {
    format!("l12/{}-{}-{}", texel[0], texel[1], texel[2])
}

/// The production entity pipelines (`Opaque` for a lit model, `Glint` for its foil) against
/// every GL case, one cell each, in one frame.
#[test]
fn entity_pipelines_match_fixed_function_gl_pixel_for_pixel() {
    let Some(mut gpu) = headless() else {
        return;
    };
    let cam = camera();
    let mut phase = EntityPhase::new(&gpu);
    let black = [0u8; 3];
    let mut texels: Vec<[u8; 3]> = vec![black];
    texels.extend(LIT_REFS.iter().map(|r| r.texel));
    texels.extend(GLINT_REFS.iter().map(|r| r.texel));
    texels.sort_unstable();
    texels.dedup();
    for texel in &texels {
        phase.upload_texture(
            &gpu,
            &texel_key(*texel),
            &[texel[0], texel[1], texel[2], 255],
            1,
            1,
        );
    }
    phase.set_lightmap(&gpu, &test_lightmap());
    phase.begin();

    let mut expected = Vec::new();
    for (index, r) in LIT_REFS.iter().enumerate() {
        let centre = cell_centre(index);
        let verts = square(centre, r.normal, r.tint);
        phase.push_blended_lit(
            &texel_key(r.texel),
            LayerBlend::Opaque,
            packed_light(r.lightmap),
            &verts,
        );
        expected.push((format!("lit #{index} {:?}", r.normal), centre, r.rgb));
    }
    for (offset, r) in GLINT_REFS.iter().enumerate() {
        let index = LIT_REFS.len() + offset;
        let centre = cell_centre(index);
        // The foil replays the model at `GL_EQUAL`: lay a black model down first, as the GL
        // reference's black clear.
        let base = square(centre, [0.0, 1.0, 0.0], [1.0; 3]);
        phase.push_blended_lit(
            &texel_key(black),
            LayerBlend::Opaque,
            packed_light(r.lightmap),
            &base,
        );
        let foil = square(centre, [0.0, 1.0, 0.0], r.color);
        phase.push_blended_lit(
            &texel_key(r.texel),
            LayerBlend::Glint,
            packed_light(r.lightmap),
            &foil,
        );
        expected.push((format!("glint #{offset} {:?}", r.color), centre, r.rgb));
    }
    assert!(
        expected.len() <= (GRID * GRID) as usize,
        "every case needs its own cell"
    );
    phase.finish(&gpu);

    let mut list = PhaseList::new();
    list.clear_color = wgpu::Color::BLACK;
    list.insert(PhaseOrder::ENTITIES, Box::new(phase));
    let frame = gpu.acquire().expect("acquire offscreen frame");
    list.render(&gpu, frame.view(), &cam, 0.0);
    frame.present(&gpu.queue);
    let pixels = gpu.read_pixels().expect("read back the frame");

    let mut mismatches = Vec::new();
    for (label, centre, gl) in &expected {
        let (x, y) = pixel_of(&cam, *centre);
        let i = ((y * SIZE + x) * 4) as usize;
        let got = [pixels[i], pixels[i + 1], pixels[i + 2]];
        if !within(got, *gl) {
            mismatches.push(format!("{label}: wgpu {got:?}, GL {gl:?}"));
        }
    }
    assert!(
        mismatches.is_empty(),
        "{} of {} cells differ from fixed-function GL by more than {TOLERANCE}:\n{}",
        mismatches.len(),
        expected.len(),
        mismatches.join("\n")
    );
}
