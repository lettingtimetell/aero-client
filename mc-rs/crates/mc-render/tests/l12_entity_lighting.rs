//! The entity pass's lighting order, checked pixel for pixel
//! against fixed-function OpenGL running vanilla 1.8.9's own lighting state.
//!
//! The tables below come from `crates/mc-client/javaref/EntityLightingRef.java` (regenerate
//! with `generate-entity-lighting.ps1`). It calls the real `RenderHelper
//! .enableStandardItemLighting`, `OpenGlHelper.setLightmapTextureCoords` and repeats
//! `EntityRenderer.enableLightmap`'s texture-unit-1 setup in an LWJGL 2 Pbuffer, draws one quad
//! per case in `ModelBox`'s vertex format through the real `Tessellator`, and reads the centre
//! pixel back. Oblique normals are an axis-aligned model normal turned by the modelview, which is
//! how an entity model produces them.
//!
//! Two things the old entity shader got wrong, both visible at night:
//!
//! * `fs` clamped `diffuse * colour * lightmap`. GL clamps the lit primary colour first and only
//!   then multiplies the texel (unit 0) and the lightmap (unit 1), so an upward face
//!   (standard-item light 1.37) under a dark lightmap came out up to 37% too bright.
//! * `fs_glint` ignored the lightmap. `RenderItem.renderEffect` and `LayerArmorBase.renderGlint`
//!   only call `disableLighting()`; unit 1 stays on through `RenderGlobal.renderEntities`, and
//!   the `GL_SRC_COLOR, GL_ONE` blend squares the result, so vanilla's foil is nearly invisible
//!   in the dark while the old shader drew it at full strength.
//!
//! The GPU test skips cleanly (printing `SKIP:`) without an adapter.

