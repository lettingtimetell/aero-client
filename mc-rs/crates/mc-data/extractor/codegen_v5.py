#!/usr/bin/env python3
"""Generate mc-data's protocol-5 (1.7.10) tables.

    python codegen_v5.py <extractor/out> <mc-data/src/v5>

Input: the committed 1.8.9 extractor output (`blocks.json`, `items.json`, `stats.json`), plus
the 1.7.10 rules written below. Output: `generated.rs` in the given directory, with three
tables: the block decode table, the 1.7.10 item overlay, and the numeric 1.7.10 statistic ids.

# The block decode table

A 1.7.10 chunk cell is `id << 4 | meta` with a 12-bit block id and a free 4-bit meta: 1.7.10
resolves the block by id alone and every block class reads the meta with its own arithmetic
(java17: `ExtendedBlockStorage.getBlockByExtId` / `getExtBlockMetadata`). 1.8.9 stores the
same packing but only accepts the values its state table registers; any other value reads as
air. The client keeps 1.8.9's storage, so every 1.7.10 cell is rewritten once, at decode time,
to a registered 1.8.9 state that behaves the same. The rules, in order:

1. A block id 1.7.10 does not register (165-169 and 176 up) is air, as in 1.7.10, whose block
   registry defaults to air (java17: `Block.registerBlocks`, `Block.blockRegistry`).
2. An explicit choice from `OVERRIDES`, for the metas below where the generic rule would not
   reproduce what the 1.7.10 block code does with that meta. Each entry cites that code.
3. A meta 1.8.9 registers for the block is kept as is. This keeps the raw 1.7.10 meta in
   storage wherever 1.8.9 can hold it, so 1.7.10 rules that read the raw meta (the fence gate
   collision axis, the powered-rail ray box) can still be applied to the stored state.
4. Any other meta becomes the state 1.8.9's `getStateFromMeta` returns for it. For every block
   outside `OVERRIDES` the 1.8.9 geometry of that state equals what the 1.7.10 block code builds
   for the raw meta, apart from the metas `tests/v5_java_dump_oracle.rs` lists with their
   java17 code (stale bounds and the like, which no 1.8.9 state reproduces).

Rule 4 never has to cover a meta for which 1.8.9's `getStateFromMeta` throws: the script
fails if one is left without an explicit choice.

# The item overlay

1.7.10 registers an item form for every block outside a fixed exclusion list (java17:
`Item.registerItems`), so it has twelve block items 1.8.9 lacks, and 1.8.9 adds 34 items. Of
the shared items, nine have a different value the client's item logic reads: stack size,
subtypes, a registry name, the held pose, two heal amounts (each patch below cites its java17
line). The overlay holds a complete `ItemProps` for each of those 21 ids, built from the 1.8.9
row (or the block, for the new block items) with the 1.7.10 values applied; every other shared
id reads the 1.8.9 table.

# The statistic table

1.7.10 names block and item statistics by numeric id (`stat.mineBlock.1`); 1.8.9 by registry
name (`stat.mineBlock.minecraft.stone`) and has no numeric alias (java17/java18:
`StatList`). A numeric 1.7.10 id resolves to the statistic 1.8.9 keeps in the same array slot,
after 1.8.9's own `replaceAllSimilarBlocks` merges, which the script replays over the extracted
statistics.
"""

import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from codegen import f32, pascal, rs  # noqa: E402  (the literal helpers of the 1.8.9 tables)

HEADER = """// @generated by crates/mc-data/extractor/codegen_v5.py -- DO NOT EDIT.
//
// Source of truth: crates/mc-data/extractor/out/{blocks,items,stats}.json and the 1.7.10
// rules in codegen_v5.py.
// Regenerate with:
//   python crates/mc-data/extractor/codegen_v5.py crates/mc-data/extractor/out crates/mc-data/src/v5
"""

# --------------------------------------------------------------------------------- items

# java17: Item.registerItems gives every block an ItemBlock except a fixed list
# (item/Item.java:252-399); java18: Item.registerItems registers block items one by one with
# registerItemBlock. These twelve have one only in 1.7.10. The two double slabs get an ItemSlab
# with subtypes.
ITEMS_ONLY_IN_1_7_10 = {
    8: "ItemBlock",
    9: "ItemBlock",
    10: "ItemBlock",
    11: "ItemBlock",
    43: "ItemSlab",
    51: "ItemBlock",
    90: "ItemBlock",
    119: "ItemBlock",
    125: "ItemSlab",
    127: "ItemBlock",
    141: "ItemBlock",
    142: "ItemBlock",
}

# 1.8.9 items 1.7.10 does not register: java18 Item.registerItems has them, java17
# Item.registerItems (item/Item.java:252-399) does not (slime, barrier, prismarine, red
# sandstone, the new fences, gates and doors, rabbit, mutton, banner, armor stand, ...).
ITEMS_ONLY_IN_1_8_9 = (
    list(range(165, 170))
    + [179, 180]
    + list(range(182, 193))
    + list(range(409, 417))
    + [423, 424, 425]
    + list(range(427, 432))
)

# Shared items whose 1.7.10 values differ, as `id -> {field: value}` over the items.json row.
ITEM_PATCHES = {
    # java17: Item.registerItems gives stone, grass and sponge a plain ItemBlock (no subtypes);
    # java18: Item.registerItems uses ItemMultiTexture for stone and sponge, ItemColored for
    # grass.
    1: {"class": "net.minecraft.item.ItemBlock", "has_subtypes": False},
    2: {"class": "net.minecraft.item.ItemBlock"},
    19: {"class": "net.minecraft.item.ItemBlock", "has_subtypes": False},
    # java17: ItemDoor.<init> sets maxStackSize = 1 (item/ItemDoor.java:19); java18: ItemDoor
    # keeps Item's 64.
    324: {"max_stack_size": 1},
    330: {"max_stack_size": 1},
    # java17: Item.registerItems names item 350 "cooked_fished" (item/Item.java:174); java18:
    # "cooked_fish" (item/Item.java:860).
    350: {"name": "minecraft:cooked_fished"},
    # java17: the blaze rod has no setFull3D (item/Item.java:193); java18: setFull3D()
    # (item/Item.java:879).
    369: {"full_3d": False},
    # java17: carrot heals 4, baked potato 6 (item/Item.java:215, 217); java18: 3 and 5
    # (item/Item.java:901, 903).
    391: {"food_heal": 4},
    393: {"food_heal": 6},
}


def item_literal(it):
    """An `ItemProps` literal, field for field as codegen.py writes the 1.8.9 table."""
    tm = it.get("tool_material")
    am = it.get("armor_material")
    return (
        "    ItemProps {{\n"
        "        id: ItemId({id}), name: {name}, unlocalized: {unloc},\n"
        "        display_name: {disp}, registered: true,\n"
        "        max_stack_size: {stack}, max_damage: {dmg}, damageable: {dmgable},\n"
        "        has_subtypes: {subs}, enchantability: {ench}, full_3d: {f3d},\n"
        "        kind: ItemKind::{kind}, tool_material: {tool}, armor_material: {armor},\n"
        "        armor_slot: {slot}, armor_reduction: {red}, attack_damage: {atk},\n"
        "        efficiency: {eff}, food_heal: {heal}, food_saturation: {sat},\n"
        "        block: {block}, creative_tab: {tab},\n"
        "        java_class: {cls},\n"
        "    }},\n"
    ).format(
        id=it["id"],
        name=rs(it["name"]),
        unloc=rs(it["unlocalized"]),
        disp=rs(it["display_name"]),
        stack=it["max_stack_size"],
        dmg=it["max_damage"],
        dmgable=str(it["damageable"]).lower(),
        subs=str(it["has_subtypes"]).lower(),
        ench=it["enchantability"],
        f3d=str(it["full_3d"]).lower(),
        kind=pascal(it["kind"]),
        tool="Some(ToolMaterial::{})".format(pascal(tm)) if tm else "None",
        armor="Some(ArmorMaterial::{})".format(pascal(am)) if am else "None",
        slot="Some({})".format(it["armor_type"]) if it["armor_type"] >= 0 else "None",
        red=it["armor_reduction"],
        atk=f32(it["attack_damage"]),
        eff=f32(it["efficiency"]),
        heal=it["food_heal"],
        sat=f32(it["food_saturation"]),
        block="Some(BlockId({}))".format(it["block_id"]) if it["block_id"] >= 0 else "None",
        tab="Some({})".format(rs(it["creative_tab"])) if it.get("creative_tab") else "None",
        cls=rs(it["class"]),
    )


def build_item_overlay(items_json, blocks_json):
    items = {it["id"]: it for it in items_json["items"]}
    blocks = {b["id"]: b for b in blocks_json["blocks"]}
    rows = []
    for item_id, cls in sorted(ITEMS_ONLY_IN_1_7_10.items()):
        assert item_id not in items, item_id
        blk = blocks[item_id]
        rows.append(
            {
                "id": item_id,
                "name": blk["name"],
                "unlocalized": blk["unlocalized"],
                "display_name": blk["display_name"],
                "max_stack_size": 64,
                "max_damage": 0,
                "damageable": False,
                "has_subtypes": cls == "ItemSlab",
                "enchantability": 0,
                "full_3d": False,
                "kind": "block",
                "tool_material": None,
                "armor_material": None,
                "armor_type": -1,
                "armor_reduction": 0,
                "attack_damage": 0.0,
                "efficiency": 0.0,
                "food_heal": 0,
                "food_saturation": 0.0,
                "block_id": item_id,
                # No creative tab: java17 Item.registerItems gives these ItemBlocks none.
                "creative_tab": None,
                "class": "net.minecraft.item." + cls,
            }
        )
    for item_id, patch in sorted(ITEM_PATCHES.items()):
        row = dict(items[item_id])
        for field, value in patch.items():
            assert field in row, (item_id, field)
            assert row[field] != value, (item_id, field, "patch changes nothing")
            row[field] = value
        rows.append(row)
    for item_id in ITEMS_ONLY_IN_1_8_9:
        assert item_id in items, item_id
    return sorted(rows, key=lambda r: r["id"])


# --------------------------------------------------------------------------------- stats

STAT_KINDS = [
    ("mine_block", "mineBlock", "V5_STATS_MINE_BLOCK"),
    ("craft_item", "craftItem", "V5_STATS_CRAFT_ITEM"),
    ("use_item", "useItem", "V5_STATS_USE_ITEM"),
    ("break_item", "breakItem", "V5_STATS_BREAK_ITEM"),
]

# java18: StatList.replaceAllSimilarBlocks, in call order, as the (first, second) blocks of each
# mergeStatBases call.
MERGES_1_8_9 = [
    ("water", "flowing_water"),
    ("lava", "flowing_lava"),
    ("lit_pumpkin", "pumpkin"),
    ("lit_furnace", "furnace"),
    ("lit_redstone_ore", "redstone_ore"),
    ("powered_repeater", "unpowered_repeater"),
    ("powered_comparator", "unpowered_comparator"),
    ("redstone_torch", "unlit_redstone_torch"),
    ("lit_redstone_lamp", "redstone_lamp"),
    ("double_stone_slab", "stone_slab"),
    ("double_wooden_slab", "wooden_slab"),
    ("double_stone_slab2", "stone_slab2"),
    ("grass", "dirt"),
    ("farmland", "dirt"),
]


def build_stats(stats_json, blocks_json):
    """`{kind: [(numeric id, 1.8.9 stat id)]}`: every array slot 1.8.9 fills after its merges."""
    block_ids = {b["name"].replace("minecraft:", ""): b["id"] for b in blocks_json["blocks"]}
    out = {}
    for kind, _, _ in STAT_KINDS:
        array = {}
        for stat in stats_json["all"]:
            if stat["kind"] == kind:
                assert stat["item_id"] not in array, stat
                array[stat["item_id"]] = stat["id"]
        # java18 StatList.mergeStatBases. `stats.json` was extracted after the merges ran, so
        # a merged-away statistic is already missing from it; replaying the merge over that
        # array still leaves every slot as Java left it (a slot Java emptied reads empty here).
        for first, second in MERGES_1_8_9:
            i, j = block_ids[first], block_ids[second]
            if array.get(i) is not None and array.get(j) is None:
                array[j] = array[i]
            else:
                array[i] = array.get(j)
        out[kind] = sorted((n, sid) for n, sid in array.items() if sid is not None)
    return out

# java17: Block.registerBlocks registers 0-164 and 170-175 (block/Block.java:171-381).
REGISTERED_1_7_10 = set(range(0, 165)) | set(range(170, 176))


def same(meta):
    return meta


def const(value):
    return lambda meta: value


def table(mapping):
    return lambda meta: mapping.get(meta)


# block id -> (rule, note). A rule returns the 1.8.9 meta for a 1.7.10 meta, or None to fall
# through to the generic rules. The note is copied into the generated table.
OVERRIDES = {
    # java17 BlockStone has no meta use at all; 1.8.9 metas 1-6 are granite..andesite.
    1: (const(0), "every meta is plain stone (java17 BlockStone reads no meta)"),
    # java17 BlockSponge has no meta use; 1.8.9 meta 1 is the wet sponge.
    19: (const(0), "every meta is a dry sponge (java17 BlockSponge reads no meta)"),
    # java17 BlockSapling.getIcon: `meta &= 7; icons[clamp(meta, 0, 5)]` (block/BlockSapling.java:49-53).
    6: (table({6: 5, 7: 5, 14: 13, 15: 13}), "6/7 draw as type 5 (java17 BlockSapling.getIcon clamp)"),
    # java17 BlockRailBase.setBlockBoundsBasedOnState: flat unless the raw meta is 2-5; the
    # powered bit is meta & 8. 1.8.9 has no curved powered rail, so the flat north-south shape.
    27: (table({6: 0, 7: 0, 14: 8, 15: 8}), "curve metas -> flat, powered bit kept"),
    28: (table({6: 0, 7: 0, 14: 8, 15: 8}), "curve metas -> flat, powered bit kept"),
    157: (table({6: 0, 7: 0, 14: 8, 15: 8}), "curve metas -> flat, powered bit kept"),
    # java17 BlockPistonBase: orientation `meta & 7` above 5 matches no case of
    # setBlockBoundsBasedOnState, so the base is a full cube (block/BlockPistonBase.java:292-300).
    29: (table({6: 2, 7: 2, 14: 2, 15: 2}), "orientation 6/7 is a full cube: unextended default"),
    33: (table({6: 2, 7: 2, 14: 2, 15: 2}), "orientation 6/7 is a full cube: unextended default"),
    # java17 BlockPistonExtension.getDirectionMeta clamps `meta & 7` to 0..5
    # (block/BlockPistonExtension.java:218-221): 6/7 are facing 5, sticky bit kept.
    34: (table({6: 5, 7: 5, 14: 13, 15: 13}), "facing clamps to 5 (java17 getDirectionMeta)"),
    36: (table({6: 5, 7: 5, 14: 13, 15: 13}), "facing clamps to 5 (java17 getDirectionMeta)"),
    # java17 BlockTorch.collisionRayTrace reads `meta & 7` (block/BlockTorch.java:204-231):
    # 9-12 trace as wall torches. Interaction wins over the drawing (standing in 1.7.10).
    50: (table({9: 1, 10: 2, 11: 3, 12: 4}), "9-12 trace as wall torches (meta & 7)"),
    75: (table({9: 1, 10: 2, 11: 3, 12: 4}), "9-12 trace as wall torches (meta & 7)"),
    76: (table({9: 1, 10: 2, 11: 3, 12: 4}), "9-12 trace as wall torches (meta & 7)"),
    # java17 BlockCrops.getIcon (meta > 7 -> 7), BlockCarrot/BlockPotato.getIcon (meta >= 7 ->
    # the ripe icon): 8-15 draw ripe; the bounds do not read the meta.
    59: (table({m: 7 for m in range(8, 16)}), "8-15 draw ripe (java17 BlockCrops.getIcon)"),
    141: (table({m: 7 for m in range(8, 16)}), "8-15 draw ripe (java17 BlockCarrot.getIcon)"),
    142: (table({m: 7 for m in range(8, 16)}), "8-15 draw ripe (java17 BlockPotato.getIcon)"),
    # java17 BlockCake: bites = meta, the box starts at (1 + 2 * meta) / 16, empty or inverted
    # from 7 on. The most-eaten registered cake is the closest 1.8.9 state.
    92: (table({m: 6 for m in range(7, 16)}), "7-15 -> 6, the closest box"),
    # java17 BlockStem.setBlockBoundsBasedOnState: height (2 * meta + 2) / 16; age 7 is the
    # tallest 1.8.9 box.
    104: (table({m: 7 for m in range(8, 16)}), "8-15 -> age 7, the closest box"),
    105: (table({m: 7 for m in range(8, 16)}), "8-15 -> age 7, the closest box"),
    # java17 BlockNetherWart.getIcon: meta >= 3 draws the last stage.
    115: (table({m: 3 for m in range(4, 16)}), "4-15 draw the last stage"),
    # java17 BlockCauldron.getRenderLiquidLevel clamps the level to 0..3.
    118: (table({m: 3 for m in range(4, 16)}), "4-15 render full"),
    # java17 BlockCocoa: age (meta & 12) >> 2 = 3 for 12-15, the icon clamps to stage 2, facing
    # is meta & 3 (block/BlockCocoa.java:34-38, 153-156).
    127: (table({m: 8 | (m & 3) for m in range(12, 16)}), "12-15 -> age 2, same facing"),
    # java17 BlockAnvil: the axis is meta & 3 and the top icon (meta >> 2) % 3 is undamaged
    # for 12-15 (block/BlockAnvil.java:42-47).
    145: (table({m: m & 3 for m in range(12, 16)}), "12-15 -> undamaged, same facing"),
    # java17 BlockHopper: fixed collision boxes; 1.8.9 has no up-facing hopper. Enabled bit
    # (meta & 8) kept.
    154: (table({1: 0, 7: 0, 9: 8, 15: 8}), "facing 1/7 -> down, enabled bit kept"),
    # java17 BlockNewLeaf.getIcon: only (meta & 3) == 1 is dark oak; bits 2-3 are decay flags.
    161: (table({m: m & 12 for m in range(16) if (m & 3) >= 2}), "types 2/3 draw as acacia"),
    # java17 BlockLog.getSideIcon/getTopIcon: icon index (meta & 3) % 2; bits 2-3 the axis.
    162: (
        table({m: (m & 12) | ((m & 3) % 2) for m in range(16) if (m & 3) >= 2}),
        "types 2/3 draw as (meta & 3) % 2",
    ),
}


def build_rows(blocks_json):
    """`rows[id]` = (name, [16 target metas] or None for air, note or None)."""
    by_id = {b["id"]: b for b in blocks_json["blocks"]}
    rows = []
    for block_id in range(256):
        if block_id not in REGISTERED_1_7_10:
            rows.append((by_id.get(block_id, {}).get("name"), None, None))
            continue
        blk = by_id[block_id]
        states = {st["meta"]: st for st in blk["states"]}
        rule, note = OVERRIDES.get(block_id, (lambda meta: None, None))
        metas = []
        for meta in range(16):
            st = states[meta]
            target = rule(meta)
            if target is None:
                if st["legal"]:
                    target = meta
                elif "get_state_from_meta_error" in st:
                    raise SystemExit(
                        "block {} meta {}: getStateFromMeta throws and no override is given".format(
                            block_id, meta
                        )
                    )
                else:
                    java_id = st["get_state_from_meta_id"]
                    assert java_id & 0x0FFF == block_id, (block_id, meta, java_id)
                    target = (java_id >> 12) & 0x0F
            if not states[target]["legal"]:
                raise SystemExit(
                    "block {} meta {} -> {}: not a registered 1.8.9 state".format(
                        block_id, meta, target
                    )
                )
            metas.append(target)
        rows.append((blk["name"], metas, note))
    return rows


def render(rows, overlay, stats):
    uses = ["use crate::block::BlockId;"]
    item_types = ["ItemId", "ItemKind", "ItemProps"]
    if any(r.get("armor_material") for r in overlay):
        item_types.insert(0, "ArmorMaterial")
    if any(r.get("tool_material") for r in overlay):
        item_types.append("ToolMaterial")
    uses.append("use crate::item::{{{}}};".format(", ".join(item_types)))
    out = [HEADER]
    out.append(
        """
//! The protocol-5 tables: the block decode table, the 1.7.10 item overlay and the numeric
//! statistic ids. See `codegen_v5.py` for the rules; the API is in the sibling modules.

// The float literals are the extractor's exact `f32` values, as in `crate::generated`.
#![allow(clippy::unreadable_literal)]
#![allow(clippy::excessive_precision)]

{uses}

// ------------------------------------------------------------------------------------- items

/// The 1.7.10 items whose `ItemProps` differ from 1.8.9's, and the twelve block items only 1.7.10
/// registers, ascending by id.
#[rustfmt::skip]
pub(crate) static V5_ITEM_OVERLAY: [ItemProps; {n_overlay}] = [
{overlay}];

/// The 1.8.9 items 1.7.10 does not register, ascending.
#[rustfmt::skip]
pub(crate) static V5_ITEMS_ONLY_IN_1_8_9: [u16; {n_only}] = [
{only}];

// ------------------------------------------------------------------------------------- stats
{stats}
// ------------------------------------------------------------------------------------ blocks

/// Per 1.7.10 block id (`0..=255`): the 1.8.9 meta each of the 16 metas becomes, or `None` when""".format(
            uses="\n".join(uses),
            n_overlay=len(overlay),
            overlay="".join(item_literal(r) for r in overlay),
            n_only=len(ITEMS_ONLY_IN_1_8_9),
            only=wrap_numbers(ITEMS_ONLY_IN_1_8_9),
            stats=render_stats(stats),
        )
    )
    out.append(
        """
/// 1.7.10 does not register the id (the cell is air).
#[rustfmt::skip]
const V5_META_REMAP: [Option<[u8; 16]>; 256] = [
"""
    )
    for block_id, (name, metas, note) in enumerate(rows):
        label = (name or "unregistered").replace("minecraft:", "")
        if metas is None:
            out.append("    // {} {}: not registered in 1.7.10\n    None,\n".format(block_id, label))
            continue
        comment = "    // {} {}".format(block_id, label)
        if note:
            comment += ": " + note
        out.append(comment + "\n")
        out.append("    Some([{}]),\n".format(", ".join(str(m) for m in metas)))
    out.append(
        """];

/// `V5_STATE_REMAP[id << 4 | meta]`: the packed 1.8.9 state for a 1.7.10 cell whose 12-bit id
/// is below 256. Every entry is a registered 1.8.9 state of the same block, or air.
pub(crate) static V5_STATE_REMAP: [u16; 4096] = build_state_remap();

const fn build_state_remap() -> [u16; 4096] {
    let mut out = [0u16; 4096];
    let mut block = 0;
    while block < 256 {
        if let Some(metas) = V5_META_REMAP[block] {
            let mut meta = 0;
            while meta < 16 {
                out[(block << 4) | meta] = ((block as u16) << 4) | metas[meta] as u16;
                meta += 1;
            }
        }
        block += 1;
    }
    out
}
"""
    )
    return "".join(out)


def wrap_numbers(values, per_line=16):
    lines = []
    for i in range(0, len(values), per_line):
        lines.append("    " + ", ".join(str(v) for v in values[i : i + per_line]) + ",\n")
    return "".join(lines)


def render_stats(stats):
    parts = []
    for kind, short, table in STAT_KINDS:
        rows = stats[kind]
        parts.append(
            "\n/// `(n, 1.8.9 id)`: the statistic 1.8.9 keeps for the 1.7.10 id `stat.{}.<n>`,\n"
            "/// ascending by `n`.\n"
            "#[rustfmt::skip]\n"
            "pub(crate) static {}: [(u16, &str); {}] = [\n{}];\n".format(
                short,
                table,
                len(rows),
                "".join("    ({}, {}),\n".format(n, rs(sid)) for n, sid in rows),
            )
        )
    return "".join(parts)


def load(src, name):
    with open(os.path.join(src, name), encoding="utf-8") as fh:
        return json.load(fh)


def main():
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    src = os.path.abspath(sys.argv[1])
    dst = os.path.abspath(sys.argv[2])
    blocks_json = load(src, "blocks.json")
    rows = build_rows(blocks_json)
    overlay = build_item_overlay(load(src, "items.json"), blocks_json)
    stats = build_stats(load(src, "stats.json"), blocks_json)
    text = render(rows, overlay, stats)
    path = os.path.join(dst, "generated.rs")
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print("  wrote {} ({} lines)".format(path, text.count("\n") + 1))


if __name__ == "__main__":
    main()
