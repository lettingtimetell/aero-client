#!/usr/bin/env python3
"""Generate mc-data's compact DEBUG_WORLD schema from the Java oracle TSV.

The TSV is already in the exact ChunkProviderDebug order. For each registry
block this derives property domains by first appearance (the Java Cartesian
product order), then preserves every row's getMetaFromState metadata byte.
"""

from __future__ import annotations

import hashlib
import json
from collections import OrderedDict
from pathlib import Path


ROOT = Path(__file__).resolve().parents[4]
SOURCE = Path(__file__).resolve().parent / "out/debug-grid.tsv"
DEST = Path(__file__).resolve().parent / "../src/generated/debug_states.rs"
EXPECTED_ROWS = 7806


def rust_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=True)


def read_rows() -> list[dict[str, object]]:
    rows = []
    with SOURCE.open(encoding="utf-8") as source:
        header = source.readline().rstrip("\n")
        expected = (
            "index\tregistry_id\tregistry_name\traw_storage_id\tmetadata\t"
            "java_state_id\tproperties"
        )
        if header != expected:
            raise ValueError(f"unexpected Java TSV header: {header!r}")
        for line in source:
            fields = line.rstrip("\n").split("\t")
            if len(fields) != 7:
                raise ValueError(f"malformed Java row: {line!r}")
            properties = OrderedDict()
            if fields[6]:
                for item in fields[6].split(";"):
                    name, value = item.split("=", 1)
                    properties[name] = value
            rows.append({
                "index": int(fields[0]),
                "block": int(fields[1]),
                "name": fields[2],
                "metadata": int(fields[4]),
                "properties": properties,
            })
    if len(rows) != EXPECTED_ROWS:
        raise ValueError(f"expected {EXPECTED_ROWS} Java rows, got {len(rows)}")
    if [int(row["index"]) for row in rows] != list(range(EXPECTED_ROWS)):
        raise ValueError("Java indices are not contiguous")
    return rows


def group_blocks(rows: list[dict[str, object]]) -> list[dict[str, object]]:
    blocks: list[dict[str, object]] = []
    by_id: OrderedDict[int, dict[str, object]] = OrderedDict()
    for row in rows:
        block = int(row["block"])
        record = by_id.get(block)
        if record is None:
            record = {
                "block": block,
                "name": row["name"],
                "rows": [],
                "domains": OrderedDict(),
            }
            by_id[block] = record
            blocks.append(record)
        elif record["name"] != row["name"]:
            raise ValueError(f"block {block} changed names")
        block_rows = record["rows"]
        assert isinstance(block_rows, list)
        block_rows.append(row)
        props = row["properties"]
        assert isinstance(props, OrderedDict)
        domains = record["domains"]
        assert isinstance(domains, OrderedDict)
        if set(domains) != set(props):
            if domains:
                raise ValueError(f"block {block} changed property names")
            for name in props:
                domains[name] = []
        for name, value in props.items():
            if value not in domains[name]:
                domains[name].append(value)

    for record in blocks:
        block_rows = record["rows"]
        domains = record["domains"]
        assert isinstance(block_rows, list) and isinstance(domains, OrderedDict)
        product = 1
        for values in domains.values():
            product *= len(values)
        if product != len(block_rows):
            raise ValueError(
                f"block {record['block']}: Cartesian product {product} != rows {len(block_rows)}"
            )
    return blocks


def render(blocks: list[dict[str, object]], source_hash: str) -> str:
    lines = [
        "// @generated by mc-rs/crates/mc-data/extractor/generate_debug_states.py -- do not edit by hand.",
        f"// Java oracle debug-grid.tsv SHA256: {source_hash}",
        "// Order: Block.blockRegistry, then BlockState.getValidStates() Cartesian tuples.",
        "// Property domains are sorted by Java IProperty name; values retain getAllowedValues iterator order.",
        "",
        "use crate::block::{DebugBlockSchema, DebugPropertySchema};",
        "",
        "/// Vanilla 1.8.9 DEBUG_WORLD schemas in Java registry order.",
        "#[rustfmt::skip]",
        "pub(crate) static DEBUG_BLOCKS: &[DebugBlockSchema] = &[",
    ]
    for record in blocks:
        domains = record["domains"]
        block_rows = record["rows"]
        assert isinstance(domains, OrderedDict) and isinstance(block_rows, list)
        lines.append("    DebugBlockSchema {")
        lines.append(f"        block: {record['block']},")
        if domains:
            lines.append("        properties: &[")
            for name, values in domains.items():
                joined = ", ".join(rust_string(value) for value in values)
                lines.append("            DebugPropertySchema {")
                lines.append(f"                name: {rust_string(name)},")
                lines.append(f"                values: &[{joined}],")
                lines.append("            },")
            lines.append("        ] as &[DebugPropertySchema],")
        else:
            lines.append("        properties: &[] as &[DebugPropertySchema],")
        metadata = ", ".join(str(int(row["metadata"])) for row in block_rows)
        lines.append(f"        metadata: &[{metadata}],")
        lines.append("    },")
    lines.extend("];")
    return "\n".join(lines) + "\n"


def main() -> None:
    rows = read_rows()
    blocks = group_blocks(rows)
    rendered = render(blocks, hashlib.sha256(SOURCE.read_bytes()).hexdigest())
    DEST.write_text(rendered, encoding="utf-8", newline="\n")
    print(f"wrote {DEST}")
    print(f"blocks={len(blocks)} rows={len(rows)} bytes={len(rendered.encode('utf-8'))}")


if __name__ == "__main__":
    main()
