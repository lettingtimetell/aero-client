RENDER_TYPE = {-1: "Invisible", 1: "Liquid", 2: "TileEntity", 3: "Model"}
RENDER_LAYER = {
    "SOLID": "Solid",
    "CUTOUT_MIPPED": "CutoutMipped",
    "CUTOUT": "Cutout",
    "TRANSLUCENT": "Translucent",
}
UNIT_BOX = [0.0, 0.0, 0.0, 1.0, 1.0, 1.0]


def collision_expr(boxes):
    if not boxes:
        return "CollisionShape::Empty"
    if len(boxes) == 1 and boxes[0] == UNIT_BOX:
        return "CollisionShape::Full"
    inner = ", ".join(
        "Aabb::new({}, {}, {}, {}, {}, {})".format(*[f64(v) for v in b]) for b in boxes
    )
    return "CollisionShape::Boxes(&[{}])".format(inner)


def aabb_expr(b):
    return "Aabb::new({}, {}, {}, {}, {}, {})".format(*[f64(v) for v in b])


def variant_key(props):
    if not props:
        return "normal"
    return ",".join("{}={}".format(k, v) for k, v in props.items())


def expected_door_properties(meta):
    """The exact `BlockDoor.getStateFromMeta` tuple for one 4-bit input."""
    if meta & 8:
        return {
            "facing": "north",
            "half": "upper",
            "hinge": "right" if meta & 1 else "left",
            "open": "false",
            "powered": "true" if meta & 2 else "false",
        }
    return {
        "facing": ("east", "south", "west", "north")[meta & 3],
        "half": "lower",
        "hinge": "left",
        "open": "true" if meta & 4 else "false",
        "powered": "false",
    }


def validate_door_metadata_tuples(blocks):
    """Reject stale door variants before generated tables hide the decoder distinction.

    `Block.getStateId` only tells us which packed storage entry a virtual decoder selected.
    For doors that is not enough evidence by itself: upper metadata's facing/open values are
    defaults, lower metadata's hinge/powered values are defaults, and 12..15 normalize to
    8..11. The extractor records the live virtual tuple so this check covers all three facts
    for every vanilla door family and confirms that its target state's generated variant agrees.
    """
    state_by_id = {
        st["state_id"]: st
        for blk in blocks
        for st in blk["states"]
        if st["legal"]
    }
    doors = [blk for blk in blocks if blk["class"] == "net.minecraft.block.BlockDoor"]
    assert len(doors) == 7, "expected the seven vanilla BlockDoor registry entries"

    for blk in doors:
        assert len(blk["states"]) == 16, blk["name"]
        for st in blk["states"]:
            meta = st["meta"]
            want = expected_door_properties(meta)
            got = st.get("get_state_from_meta_properties")
            assert got == want, (blk["name"], meta, "getStateFromMeta tuple", got, want)

            java_state_id = st["get_state_from_meta_id"]
            canonical_storage_id = ((java_state_id & 0x0FFF) << 4) | ((java_state_id >> 12) & 0x0F)
            canonical = state_by_id.get(canonical_storage_id)
            assert canonical is not None, (blk["name"], meta, "unregistered canonical state")
            expected_meta = meta if meta & 8 == 0 else 8 | (meta & 3)
            assert canonical["state_id"] == (blk["id"] << 4 | expected_meta), (
                blk["name"], meta, "canonical packed state",
            )


def gen_blocks(data, mat_map, out_dir):
    blocks = data["blocks"]
    n_states = 4096

    validate_door_metadata_tuples(blocks)

    props = Dedup()
    variants = Dedup()

    # Slot 0 is the sentinel every illegal / out-of-range state resolves to. It is air
    # with `legal: false`, which is exactly what ExtendedBlockStorage.get() does in 1.8.9.
    air_block = next(b for b in blocks if b["id"] == 0)

    def render_props(blk, st, legal):
        return (
            "    BlockProps {{\n"
            "        collision: {collision},\n"
            "        light_emission: {light}, light_opacity: {opacity}, hardness: {hardness},\n"
            "        render_type: RenderType::{rtype}, material: {material},\n"
            "        block: BlockId({bid}), legal: {legal},\n"
            "        bounds: {bounds}, render_layer: RenderLayer::{layer},\n"
            "        resistance: {resistance}, slipperiness: {slip},\n"
            "        ambient_occlusion_light: {ao}, map_color: {mapcolor},\n"
            "        opaque_cube: {opaque}, full_cube: {full_cube}, full_block: {full_block},\n"
            "        normal_cube: {normal}, visually_opaque: {vis}, translucent: {trans},\n"
            "        use_neighbor_brightness: {unb}, has_tile_entity: {te},\n"
            "        passable: {passable}, collision_depends_on_neighbors: {dyn_},\n"
            "    }},"
        ).format(
            collision=collision_expr(st.get("collision", [])),
            light=blk["light_value"],
            opacity=blk["light_opacity"],
            hardness=f32(st.get("hardness_state", blk["hardness"])),
            rtype=RENDER_TYPE.get(blk["render_type"], "Model"),
            material=mat_map.get(blk["material"], "Material::Air"),
            bid=blk["id"],
            legal=str(legal).lower(),
            bounds=aabb_expr(st.get("bounds", UNIT_BOX)),
            layer=RENDER_LAYER.get(blk["render_layer"], "Solid"),
            resistance=f32(blk["resistance"]),
            slip=f32(blk["slipperiness"]),
            ao=f32(blk["ambient_occlusion_light"]),
            mapcolor=st.get("map_color", 0) & 0xFFFFFF,
            opaque=str(blk["opaque_cube"]).lower(),
            full_cube=str(blk["full_cube"]).lower(),
            full_block=str(blk["full_block"]).lower(),
            normal=str(blk["normal_cube"]).lower(),
            vis=str(blk["visually_opaque"]).lower(),
            trans=str(blk["translucent"]).lower(),
            unb=str(blk["use_neighbor_brightness"]).lower(),
            te=str(blk["tile_entity"]).lower(),
            passable=str(st.get("passable", True)).lower(),
            dyn_=str(st.get("collision_depends_on_neighbors", False)).lower(),
        )

    sentinel_state = {
        "meta": 0,
        "collision": [],
        "bounds": UNIT_BOX,
        "map_color": 0,
        "passable": True,
        "hardness_state": air_block["hardness"],
        "collision_depends_on_neighbors": False,
    }
    assert props.intern("SENTINEL", render_props(air_block, sentinel_state, False)) == 0
    assert variants.intern("normal", ("normal", "&[]")) == 0

    state_props = [0] * n_states
    state_variant = [0] * n_states
    java_state_variant = [0] * n_states
    # `Block.getStateById` is *not* the chunk-storage `BLOCK_STATE_IDS` lookup. It first
    # selects a block by id and then invokes that block's `getStateFromMeta`. The extractor
    # records the resulting state through `Block.getStateId`, so this is an exact generated
    # image of the virtual Java method for every registered block and 4-bit metadata value.
    # The remaining 12-bit block-id space is unregistered and therefore resolves through
    # vanilla's default block registry entry, `minecraft:air` (slot 0).
    java_state_from_id = [0] * n_states

    for blk in blocks:
        for st in blk["states"]:
            sid = st["state_id"]
            if "get_state_from_meta_error" in st:
                # `Block.getStateById` propagates this virtual-decoder failure. `u16::MAX`
                # is outside the generated state-id range and is handled explicitly by the
                # public decoder rather than being mistaken for air.
                java_state_from_id[sid] = 0xFFFF
            else:
                java_state_id = st["get_state_from_meta_id"]
                java_block = java_state_id & 0x0FFF
                java_meta = (java_state_id >> 12) & 0x0F
                canonical = (java_block << 4) | java_meta
                assert canonical < n_states, (blk["id"], st["meta"], java_state_id)
                java_state_from_id[sid] = canonical

            if not st["legal"]:
                continue
            rendered = render_props(blk, st, True)
            state_props[sid] = props.intern(rendered, rendered)
            vprops = st.get("properties", {})
            key = variant_key(vprops)
            pairs = "&[{}]".format(
                ", ".join("({}, {})".format(rs(k), rs(v)) for k, v in vprops.items())
            )
            state_variant[sid] = variants.intern((key, pairs), (key, pairs))

    # Most virtual metadata decoders select one of the registry's stored property tuples, so
    # their variant identity can reuse its target state. Doors are the exception: the 4-bit
    # encoding drops two properties per half and `getStateFromMeta` supplies Java defaults that
    # differ from `BLOCK_STATE_IDS`' arbitrary representative for the same packed state id.
    # Keep a decoder-context table rather than corrupting the raw chunk-storage variant table.
    for blk in blocks:
        for st in blk["states"]:
            sid = st["state_id"]
            if "get_state_from_meta_error" in st:
                continue
            canonical = java_state_from_id[sid]
            assert canonical != 0xFFFF
            vprops = st.get("get_state_from_meta_properties")
            if vprops is None:
                java_state_variant[sid] = state_variant[canonical]
                continue
            key = variant_key(vprops)
            pairs = "&[{}]".format(
                ", ".join("({}, {})".format(rs(k), rs(v)) for k, v in vprops.items())
            )
            java_state_variant[sid] = variants.intern((key, pairs), (key, pairs))

    L = [HEADER.format(src="blocks.json")]
    L.append("")
    L.append("use crate::block::{Aabb, BlockId, BlockProps, CollisionShape, RenderLayer, RenderType};")
    L.append("use crate::generated::materials::Material;")
    L.append("use crate::item::ItemId;")
    L.append("")
    L.append("/// Highest block id vanilla 1.8.9 registers (`minecraft:double_plant` family aside).")
    L.append("pub const MAX_BLOCK_ID: u16 = {};".format(max(b["id"] for b in blocks)))
    L.append("")
    L.append("/// Number of packed `block_id << 4 | meta` states the tables cover.")
    L.append("pub const STATE_COUNT: usize = {};".format(n_states))
    L.append("")
    L.append("/// Deduplicated per-state properties. Index via [`STATE_PROPS`]; slot 0 is the")
    L.append("/// air sentinel that every illegal state resolves to.")
    L.append("pub(crate) static BLOCK_PROPS: [BlockProps; {}] = [".format(len(props.items)))
    L.extend(props.items)
    L.append("];")
    L.append("")
    L.append("/// `packed state id -> index into BLOCK_PROPS`. Illegal states map to 0 (air).")
    L.append("pub(crate) static STATE_PROPS: [u16; STATE_COUNT] = [")
    for i in range(0, n_states, 32):
        L.append("    " + " ".join("{},".format(v) for v in state_props[i : i + 32]))
    L.append("];")
    L.append("")
    L.append("/// `block_id << 4 | input_meta` -> the packed state from Java's")
    L.append("/// `Block.getStateById` / virtual `Block.getStateFromMeta` decoder.")
    L.append("///")
    L.append("/// This intentionally differs from [`STATE_PROPS`], which models chunk storage's")
    L.append("/// `BLOCK_STATE_IDS` lookup. Entries above the generated 8-bit id range are air;")
    L.append("/// `getBlockById` returns the registry default (`minecraft:air`) for them.")
    L.append("pub(crate) static JAVA_STATE_FROM_ID: [u16; STATE_COUNT] = [")
    for i in range(0, n_states, 32):
        L.append("    " + " ".join("{},".format(v) for v in java_state_from_id[i : i + 32]))
    L.append("];")
    L.append("")
    L.append("/// `Block.getStateById` input -> index into STATE_VARIANTS. This keeps virtual")
    L.append("/// metadata-decoder defaults distinct from the raw chunk-storage state tuple.")
    L.append("pub(crate) static JAVA_STATE_VARIANT_IDX: [u16; STATE_COUNT] = [")
    for i in range(0, n_states, 32):
        L.append("    " + " ".join("{},".format(v) for v in java_state_variant[i : i + 32]))
    L.append("];")
    L.append("")
    L.append("/// `packed state id -> index into STATE_VARIANTS`.")
    L.append("pub(crate) static STATE_VARIANT_IDX: [u16; STATE_COUNT] = [")
    for i in range(0, n_states, 32):
        L.append("    " + " ".join("{},".format(v) for v in state_variant[i : i + 32]))
    L.append("];")
    L.append("")
    L.append("/// Deduplicated blockstate variant keys: the `facing=east,half=bottom` strings")
    L.append("/// vanilla's `assets/minecraft/blockstates/*.json` files are keyed by, plus the")
    L.append("/// same data split into (property, value) pairs. `normal` when a block has no")
    L.append("/// properties, matching `StateMapperBase.getPropertyString`.")
    L.append(
        "pub(crate) static STATE_VARIANTS: [(&str, &[(&str, &str)]); {}] = [".format(
            len(variants.items)
        )
    )
    for key, pairs in variants.items:
        L.append("    ({}, {}),".format(rs(key), pairs))
    L.append("];")
    L.append("")
    L.append("/// Per-block (not per-state) registry data.")
    L.append("pub(crate) static BLOCK_INFO: [crate::block::BlockInfo; {}] = [".format(len(blocks)))
    by_id = {b["id"]: b for b in blocks}
    max_id = max(by_id)
    for bid in range(max_id + 1):
        b = by_id.get(bid)
        if b is None:
            L.append(
                "    crate::block::BlockInfo {{ id: BlockId({}), name: \"\", unlocalized: \"\", "
                "display_name: \"\", registered: false, item: None, step_sound: \"\", break_sound: \"\", "
                "step_sound_volume: 1f32, step_sound_pitch: 1f32, java_class: \"\", "
                "mobility_flag: 0, default_meta: 0 }},".format(bid)
            )
            continue
        item = b["item_id"]
        item_expr = "Some(ItemId({}))".format(item) if item and item > 0 else "None"
        L.append(
            "    crate::block::BlockInfo {{ id: BlockId({id}), name: {name}, unlocalized: {unloc}, "
            "display_name: {disp}, registered: true, item: {item}, step_sound: {snd}, break_sound: {break_snd}, "
            "step_sound_volume: {vol}, step_sound_pitch: {pitch}, java_class: {cls}, "
            "mobility_flag: {mob}, default_meta: {default_meta} }},".format(
                id=b["id"],
                name=rs(b["name"]),
                unloc=rs(b["unlocalized"]),
                disp=rs(b["display_name"]),
                item=item_expr,
                snd=rs(b["step_sound"]),
                break_snd=rs(b["break_sound"]),
                vol=f32(b["step_sound_volume"]),
                pitch=f32(b["step_sound_pitch"]),
                cls=rs(b["class"]),
                mob=b["mobility_flag"],
                default_meta=b["default_meta"],
            )
        )
    L.append("];")
    L.append("")
    L.append("/// `(registry name, block id)` sorted by name, for binary search.")
    names = sorted((b["name"], b["id"]) for b in blocks)
    L.append("pub(crate) static BLOCK_NAMES: [(&str, u16); {}] = [".format(len(names)))
    for name, bid in names:
        L.append("    ({}, {}),".format(rs(name), bid))
    L.append("];")
    L.append("")
    write(os.path.join(out_dir, "blocks.rs"), "\n".join(L))
    return len(props.items), sum(1 for v in state_props if v != 0)


