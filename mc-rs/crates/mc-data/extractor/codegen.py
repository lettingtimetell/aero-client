def gen_entities(data, out_dir):
    ents = sorted(data["entities"], key=lambda e: e["net_id"])
    idents = []
    seen = set()
    for e in ents:
        base = pascal(e["name"] or e["class"].rsplit(".", 1)[-1])
        ident = base
        n = 2
        while ident in seen:
            ident = "{}{}".format(base, n)
            n += 1
        seen.add(ident)
        idents.append(ident)

    L = [HEADER.format(src="entities.json")]
    L.append("")
    L.append("use crate::entity::EntityInfo;")
    L.append("")
    L.append("/// A vanilla entity type, keyed by its 1.8.9 network id (`EntityList`).")
    L.append("///")
    L.append("/// These are the ids carried by `S0FPacketSpawnMob`. Object entities spawned by")
    L.append("/// `S0EPacketSpawnObject` use a *different*, hard-coded id space - see")
    L.append("/// [`crate::entity::ObjectType`].")
    L.append("#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]")
    L.append("#[repr(u8)]")
    L.append("pub enum EntityType {")
    for e, i in zip(ents, idents):
        L.append("    {}".format(doc("`{}` (network id {}).".format(e["name"], e["net_id"]))))
        L.append("    {},".format(i))
    L.append("}")
    L.append("")
    L.append("pub(crate) static ENTITY_INFO: [EntityInfo; {}] = [".format(len(ents)))
    for e in ents:
        L.append(
            "    EntityInfo {{ net_id: {nid}, name: {name}, java_class: {cls}, living: {liv}, "
            "width: {w}, height: {h}, eye_height: {eh}, can_be_collided_with: {collidable}, "
            "collision_border_size: {border}, render_distance_weight: {weight}, "
            "egg_primary: {ep}, egg_secondary: {es} }},".format(
                nid=e["net_id"],
                name=rs(e["name"]),
                cls=rs(e["class"]),
                liv=str(e["living"]).lower(),
                w=f32(e["width"]),
                h=f32(e["height"]),
                eh=f32(e["eye_height"]),
                collidable=str(e["can_be_collided_with"]).lower(),
                border=f32(e["collision_border_size"]),
                weight=f64(e["render_distance_weight"]),
                ep="Some({})".format(e["egg_primary"]) if e["egg_primary"] >= 0 else "None",
                es="Some({})".format(e["egg_secondary"]) if e["egg_secondary"] >= 0 else "None",
            )
        )
    L.append("];")
    L.append("")
    L.append("/// `network id -> EntityType`, or `None` for the ids vanilla never assigns.")
    L.append("pub(crate) static ENTITY_BY_NET_ID: [Option<EntityType>; 256] = [")
    table = ["None"] * 256
    for e, i in zip(ents, idents):
        table[e["net_id"]] = "Some(EntityType::{})".format(i)
    for i in range(0, 256, 8):
        L.append("    " + " ".join("{},".format(v) for v in table[i : i + 8]))
    L.append("];")
    L.append("")
    write(os.path.join(out_dir, "entities.rs"), "\n".join(L))
    return len(ents)


