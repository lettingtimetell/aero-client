def gen_mod(out_dir):
    L = [HEADER.format(src="all of them")]
    L.append("")
    L.append("//! Generated tables. Every item here is produced by `extractor/codegen.py`;")
    L.append("//! the hand-written API that wraps them lives in the parent modules.")
    L.append("")
    L.append("#![allow(clippy::unreadable_literal)]")
    L.append("#![allow(clippy::excessive_precision)]")
    L.append("")
    for m in [
        "achievements",
        "biomes",
        "blocks",
        # DEBUG_WORLD is generated by generate_debug_states.py from the Java oracle TSV.
        "debug_states",
        "enchantments",
        "entities",
        "items",
        "materials",
        "potions",
        "sounds",
    ]:
        L.append("pub(crate) mod {};".format(m))
    L.append("")
    write(os.path.join(out_dir, "mod.rs"), "\n".join(L))


def main():
    if len(sys.argv) < 3:
        print(__doc__)
        return 2
    src = os.path.abspath(sys.argv[1])
    dst = os.path.abspath(sys.argv[2])
    os.makedirs(dst, exist_ok=True)
    # Derived from this file, NOT from `src` -- `src` is routinely a scratch directory.
    repo_root = repo_root_from_here()

    def load(name):
        with open(os.path.join(src, name), "r", encoding="utf-8") as fh:
            return json.load(fh)

    print("codegen: {} -> {}".format(src, dst))
    # Preflight, before a single file is written: the sound table and the blockstate check
    # both need `repo_root`, and both are reached *after* six tables have been emitted. A
    # late failure would leave `src/generated/` half-rewritten.
    for what, path in [
        ("asset index", os.path.join(repo_root, ASSET_INDEX)),
        ("vanilla jar", os.path.join(repo_root, VANILLA_JAR)),
    ]:
        if not os.path.isfile(path):
            raise ExtractorInputMissing(
                "{} not found at {}\n"
                "  repo root resolved to {} (override with MC_REPO_ROOT)".format(
                    what, path, repo_root
                )
            )

    mat_map = gen_materials(load("materials.json"), dst)
    blocks_doc = load("blocks.json")
    n_props, n_states = gen_blocks(blocks_doc, mat_map, dst)
    n_items = gen_items(load("items.json"), dst)
    n_ents = gen_entities(load("entities.json"), dst)
    n_biomes = gen_biomes(load("biomes.json"), dst)
    n_pots = gen_potions(load("potions.json"), dst)
    n_ench = gen_enchantments(load("enchantments.json"), dst)
    n_snd = gen_sounds(load_sounds(repo_root), dst)
    n_ach = gen_achievements(load("achievements.json"), dst)
    n_stats, n_general, n_block_stats, n_item_stats, n_mob_stats = gen_stats(
        load("stats.json"), dst
    )
    gen_mod(dst)
    validate_blockstates(blocks_doc["blocks"], repo_root)
    print(
        "  {} legal states -> {} unique prop rows, {} items, {} entities, {} biomes, "
        "{} potions, {} enchantments, {} sound events, {} achievements, "
        "{} stats ({} general, {} block, {} item, {} mob rows)".format(
            n_states, n_props, n_items, n_ents, n_biomes, n_pots, n_ench, n_snd, n_ach,
            n_stats, n_general, n_block_stats, n_item_stats, n_mob_stats
        )
    )
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except ExtractorInputMissing as e:
        # Exit non-zero and say what is missing. run.ps1 gates on $LASTEXITCODE.
        sys.stderr.write("codegen.py: missing vanilla input\n  {}\n".format(e))
        sys.exit(3)
