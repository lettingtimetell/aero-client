def gen_materials(data, out_dir):
    mats = data["materials"]
    names = [m["name"] for m in mats]
    idents = [pascal(n) for n in names]

    L = [HEADER.format(src="materials.json")]
    L.append("")
    L.append("/// A block material: 1.8.9's `net.minecraft.block.material.Material`.")
    L.append("///")
    L.append("/// Physics (friction, movement blocking), the mesher (light blocking) and")
    L.append("/// tool-speed logic all key off this.")
    L.append("#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]")
    L.append("#[repr(u8)]")
    L.append("pub enum Material {")
    for n, i in zip(names, idents):
        L.append("    {}".format(doc("`Material.{}`".format(n))))
        L.append("    {},".format(i))
    L.append("}")
    L.append("")
    L.append("/// Per-material flags, mirroring the `Material` accessors in 1.8.9.")
    L.append("#[derive(Debug, Clone, Copy, PartialEq, Eq)]")
    L.append("pub struct MaterialInfo {")
    for field, ty, why in [
        ("name", "&'static str", "Vanilla field name on `Material`, e.g. `packedIce`."),
        ("liquid", "bool", "`Material::isLiquid` - water and lava."),
        ("solid", "bool", "`Material::isSolid`."),
        ("blocks_light", "bool", "`Material::blocksLight`."),
        ("blocks_movement", "bool", "`Material::blocksMovement` - false for cobwebs and plants."),
        ("can_burn", "bool", "`Material::getCanBurn`."),
        ("replaceable", "bool", "`Material::isReplaceable` - snow layers, tall grass, liquids."),
        ("opaque", "bool", "`Material::isOpaque`."),
        ("tool_not_required", "bool", "`Material::isToolNotRequired`."),
        ("mobility_flag", "u8", "`Material::getMaterialMobility`: 0 normal, 1 destroyed by pistons, 2 immovable."),
        ("map_color", "u32", "Packed RGB of the material's default map colour."),
    ]:
        L.append("    {}".format(doc(why)))
        L.append("    pub {}: {},".format(field, ty))
    L.append("}")
    L.append("")
    L.append("static MATERIAL_INFO: [MaterialInfo; {}] = [".format(len(mats)))
    for m in mats:
        L.append(
            "    MaterialInfo {{ name: {}, liquid: {}, solid: {}, blocks_light: {}, "
            "blocks_movement: {}, can_burn: {}, replaceable: {}, opaque: {}, "
            "tool_not_required: {}, mobility_flag: {}, map_color: {} }},".format(
                rs(m["name"]),
                str(m["liquid"]).lower(),
                str(m["solid"]).lower(),
                str(m["blocks_light"]).lower(),
                str(m["blocks_movement"]).lower(),
                str(m["can_burn"]).lower(),
                str(m["replaceable"]).lower(),
                str(m["opaque"]).lower(),
                str(m["tool_not_required"]).lower(),
                m["mobility_flag"],
                m["map_color"] & 0xFFFFFF,
            )
        )
    L.append("];")
    L.append("")
    L.append("impl Material {")
    L.append("    /// Flags for this material. `O(1)`, no allocation.")
    L.append("    #[inline]")
    L.append("    #[must_use]")
    L.append("    pub fn info(self) -> &'static MaterialInfo {")
    L.append("        &MATERIAL_INFO[self as usize]")
    L.append("    }")
    for field, ty in [
        ("name", "&'static str"),
        ("liquid", "bool"),
        ("solid", "bool"),
        ("blocks_light", "bool"),
        ("blocks_movement", "bool"),
        ("can_burn", "bool"),
        ("replaceable", "bool"),
        ("opaque", "bool"),
        ("tool_not_required", "bool"),
        ("mobility_flag", "u8"),
        ("map_color", "u32"),
    ]:
        getter = "is_{}".format(field) if field in ("liquid", "solid", "opaque", "replaceable") else field
        L.append("")
        L.append("    /// See [`MaterialInfo::{}`].".format(field))
        L.append("    #[inline]")
        L.append("    #[must_use]")
        L.append("    pub fn {}(self) -> {} {{".format(getter, ty))
        L.append("        self.info().{}".format(field))
        L.append("    }")
    L.append("}")
    L.append("")
    write(os.path.join(out_dir, "materials.rs"), "\n".join(L))
    return {n: "Material::" + i for n, i in zip(names, idents)}


