    L.append("#[repr(u8)]")
    L.append("pub enum ArmorMaterial {")
    for t in armor_mats:
        L.append("    {}".format(doc("`ArmorMaterial.{}`.".format(t["name"]))))
        L.append("    {},".format(pascal(t["name"])))
    L.append("}")
    L.append("")
    L.append("/// Statistics for an armour tier.")
    L.append("#[derive(Debug, Clone, Copy, PartialEq)]")
    L.append("pub struct ArmorMaterialInfo {")
    L.append("    /// Vanilla enum name, e.g. `DIAMOND`.")
    L.append("    pub name: &'static str,")
    L.append("    /// Durability multiplier applied to the per-slot base durability.")
    L.append("    pub max_damage_factor: u32,")
    L.append("    /// Enchantability weight.")
    L.append("    pub enchantability: u8,")
    L.append("}")
    L.append("")
    L.append("static ARMOR_MATERIALS: [ArmorMaterialInfo; {}] = [".format(len(armor_mats)))
