def gen_items(data, out_dir):
    items = data["items"]
    tool_mats = data["tool_materials"]
    armor_mats = data["armor_materials"]

    L = [HEADER.format(src="items.json")]
    L.append("")
    L.append("use crate::block::BlockId;")
    L.append("use crate::item::{FoodStats, ItemId, ItemProps};")
    L.append("")
    L.append("/// Broad item category, derived from the vanilla `Item` subclass.")
    L.append("#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]")
    L.append("#[repr(u8)]")
    L.append("pub enum ItemKind {")
