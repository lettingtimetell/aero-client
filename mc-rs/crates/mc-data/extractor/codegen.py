# ---------------------------------------------------------------- statistics


def gen_stats(data, out_dir):
    stats = data["all"]
    by_id = {row["id"]: i for i, row in enumerate(stats)}
    if len(by_id) != len(stats):
        raise ValueError("stats.json contains duplicate stat ids")

    kind = {
        "general": "General",
        "mine_block": "MineBlock",
        "craft_item": "CraftItem",
        "use_item": "UseItem",
        "break_item": "BreakItem",
        "kill_entity": "KillEntity",
        "entity_killed_by": "EntityKilledBy",
        "achievement": "Achievement",
    }
    formatter = {
        "simple": "Simple",
        "time": "Time",
        "distance": "Distance",
        "damage": "Damage",
    }

    L = [HEADER.format(src="stats.json")]
    L.append("")
    L.append("use crate::block::BlockId;")
    L.append("use crate::item::ItemId;")
    L.append("use crate::stat::{")
    L.append("    BlockStatAssociation, ItemStatAssociation, MobStatAssociation, StatFormat,")
    L.append("    StatInfo, StatKind,")
    L.append("};")
    L.append("")
    L.append("pub(super) static ALL_STATS: [StatInfo; {}] = [".format(len(stats)))
    for row in stats:
        item = "Some(ItemId({}))".format(row["item_id"]) if row["item_id"] is not None else "None"
        L.append(
            "    StatInfo {{ id: {id}, translation_key: {key}, display_en_us: {display}, "
            "format: StatFormat::{fmt}, independent: {independent}, kind: StatKind::{kind}, "
            "item: {item} }},".format(
                id=rs(row["id"]),
                key=rs(row["translation_key"]),
                display=rs(row["display_en_us"]),
                fmt=formatter[row["formatter"]],
                independent=str(row["independent"]).lower(),
                kind=kind[row["kind"]],
                item=item,
            )
        )
    L.append("];\n")

    sorted_ids = sorted((row["id"], i) for i, row in enumerate(stats))
    L.append("pub(super) static STAT_IDS_SORTED: [(&str, usize); {}] = [".format(len(sorted_ids)))
    for stat_id, index in sorted_ids:
        L.append("    ({}, {}),".format(rs(stat_id), index))
    L.append("];\n")

    general = data["general"]
    L.append("pub(super) static GENERAL_STAT_INDEXES: [usize; {}] = [".format(len(general)))
    for stat_id in general:
        if stat_id not in by_id:
            raise ValueError("general stat absent from allStats: {}".format(stat_id))
        L.append("    {},".format(by_id[stat_id]))
    L.append("];\n")

    def opt(value):
        return "Some({})".format(rs(value)) if value is not None else "None"

    blocks = data["blocks"]
    L.append("pub(super) static BLOCK_STATS: [BlockStatAssociation; {}] = [".format(len(blocks)))
    for row in blocks:
        L.append(
            "    BlockStatAssociation {{ block: BlockId({block}), item: ItemId({item}), "
            "mined: {mined}, crafted: {crafted}, used: {used} }},".format(
                block=row["block_id"],
                item=row["item_id"],
                mined=rs(row["mined"]),
                crafted=opt(row["crafted"]),
                used=opt(row["used"]),
            )
        )
    L.append("];\n")

    items = data["items"]
    L.append("pub(super) static ITEM_STATS: [ItemStatAssociation; {}] = [".format(len(items)))
    for row in items:
        L.append(
            "    ItemStatAssociation {{ item: ItemId({item}), depleted: {depleted}, "
            "crafted: {crafted}, used: {used} }},".format(
                item=row["item_id"],
                depleted=opt(row["depleted"]),
                crafted=opt(row["crafted"]),
                used=rs(row["used"]),
            )
        )
    L.append("];\n")

    mobs = data["mobs"]
    L.append("pub(super) static MOB_STATS: [MobStatAssociation; {}] = [".format(len(mobs)))
    for row in mobs:
        if row["killed"] is None or row["killed_by"] is None:
            raise ValueError("spawn-egg mob has no kill statistics: {}".format(row["entity_name"]))
        L.append(
            "    MobStatAssociation {{ entity_id: {entity}, entity_name: {name}, "
            "killed: {killed}, killed_by: {killed_by} }},".format(
                entity=row["entity_id"],
                name=rs(row["entity_name"]),
                killed=rs(row["killed"]),
                killed_by=rs(row["killed_by"]),
            )
        )
    L.append("];\n")

    write(os.path.join(out_dir, "stats.rs"), "\n".join(L))
    return len(stats), len(general), len(blocks), len(items), len(mobs)


