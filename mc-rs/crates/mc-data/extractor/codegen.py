def load_sounds(repo_root):
    """The 734-entry sound registry, from `jars/assets`.

    Raises rather than returning `{}` when anything is missing. The previous behaviour --
    print a WARNING and carry on -- wrote a **valid, empty** `sounds.rs`, so a regenerate
    against a checkout with no assets silently deleted the whole sound registry and exited 0.
    A missing input is a hard error here for the same reason `validate_blockstates` no longer
    skips: a green run that produced nothing reads as a green run.
    """
    index = os.path.join(repo_root, ASSET_INDEX)
    if not os.path.isfile(index):
        raise ExtractorInputMissing(
            "no asset index at {}\n"
            "  sounds.rs would be generated EMPTY and the run would still exit 0.".format(index)
        )
    with open(index, "r", encoding="utf-8") as fh:
        objects = json.load(fh)["objects"]
    entry = objects.get("minecraft/sounds.json")
    if entry is None:
        raise ExtractorInputMissing(
            "minecraft/sounds.json missing from the asset index {}".format(index)
        )
    h = entry["hash"]
    blob = os.path.join(repo_root, ASSET_OBJECTS, h[:2], h)
    if not os.path.isfile(blob):
        raise ExtractorInputMissing("asset object {} not on disk".format(blob))
    with open(blob, "r", encoding="utf-8") as fh:
        return json.load(fh)


def gen_sounds(sounds, out_dir):
    names = sorted(sounds)
    L = [HEADER.format(src="jars/assets (minecraft/sounds.json)")]
    L.append("")
    L.append("use crate::misc::SoundEvent;")
    L.append("")
    L.append("/// Every sound event vanilla 1.8.9 knows, sorted by name for binary search.")
    L.append("///")
    L.append("/// 1.8.9 has no numeric sound registry - `S29PacketSoundEffect` carries the name")
    L.append("/// as a string - so this table exists to validate and categorise what a server sends.")
    L.append("pub(crate) static SOUND_EVENTS: [SoundEvent; {}] = [".format(len(names)))
    for n in names:
        entry = sounds[n] if isinstance(sounds[n], dict) else {}
        cat = entry.get("category", "master")
        variants = entry.get("sounds", [])
        L.append(
            "    SoundEvent {{ name: {}, category: {}, variants: {} }},".format(
                rs(n), rs(cat), len(variants)
            )
        )
    L.append("];")
    L.append("")
    write(os.path.join(out_dir, "sounds.rs"), "\n".join(L))
    return len(names)


# ----------------------------------------------------------- asset validation

VANILLA_JAR = os.path.join("MCP-919-main", "jars", "versions", "1.8.9", "1.8.9.jar")


def validate_blockstates(blocks, repo_root):
    """Sanity-check the *extracted* variant keys against `assets/minecraft/blockstates/*.json`.

    **This is not the W-ACTUALSTATE oracle and must not be read as one.** It keys on the raw
    stored-metadata property string with no state mapper, so its ceiling is ~645 of vanilla's
    2,557 declared `ModelResourceLocation`s even when everything is correct. The real
    measurement runs `mc_assets::model::state_mapper::resolve`, the ~200 lines of ported
    `BlockModelShapes` registrations, and lives where that code does:

        cargo test -p mc-assets --test blockstate_coverage

    What this pass is still good for: it proves the *extractor's* property names and values
    line up with the property strings vanilla's own JSON is keyed by, before the state mapper
    ever gets involved. A rename or a case change in `emitState` shows up here first.

    It **raises** rather than skipping when the jar is absent -- see `ExtractorInputMissing`.
    Its previous "skipping" branch fired on every regenerate into a scratch directory and
    exited 0, so the check reported success without having opened a single file.
    """
    jar = os.path.join(repo_root, VANILLA_JAR)
    if not os.path.isfile(jar):
        raise ExtractorInputMissing(
            "no vanilla jar at {}\n"
            "  the blockstate check cannot run. It used to print 'skipping' and return\n"
            "  green here, which is how a validator comes to certify nothing.\n"
            "  Set MC_REPO_ROOT if your checkout is laid out differently.".format(jar)
        )
    ok = 0
    missing_file = []
    mismatched = {}
    declared_total = 0
    with zipfile.ZipFile(jar) as z:
        names = set(z.namelist())
        declared_files = [
            n
            for n in names
            if n.startswith("assets/minecraft/blockstates/") and n.endswith(".json")
        ]
        if not declared_files:
            raise ExtractorInputMissing(
                "{} has no assets/minecraft/blockstates/*.json -- wrong jar?".format(jar)
            )
        for n in declared_files:
            with z.open(n) as fh:
                declared_total += len(json.load(fh).get("variants", {}))
        for blk in blocks:
            short = blk["name"].split(":", 1)[-1]
            path = "assets/minecraft/blockstates/{}.json".format(short)
            if path not in names:
                missing_file.append(short)
                continue
            with z.open(path) as fh:
                variants = json.load(fh).get("variants", {})
            for st in blk["states"]:
                if not st["legal"]:
                    continue
                key = variant_key(st.get("properties", {}))
                if key in variants:
                    ok += 1
                else:
                    mismatched.setdefault(short, []).append(key)
    print(
        "  blockstate check: {} states matched a variant key by stored metadata alone "
        "(of {} declared across {} files); {} blocks have no same-named blockstates file, "
        "{} blocks need a custom state mapper".format(
            ok, declared_total, len(declared_files), len(missing_file), len(mismatched)
        )
    )
    print(
        "    NOT a coverage measurement -- no state mapper is applied here. "
        "Run `cargo test -p mc-assets --test blockstate_coverage` for that."
    )
    if missing_file:
        print("    no blockstates json: {}".format(", ".join(sorted(missing_file))))
    for name in sorted(mismatched):
        keys = mismatched[name]
        print("    custom mapper needed: {} ({} states, e.g. {})".format(name, len(keys), keys[0]))


