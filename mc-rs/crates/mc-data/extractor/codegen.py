class ExtractorInputMissing(Exception):
    """A vanilla input this script needs is not on disk.

    Raised, never swallowed. Both places that used to swallow it -- `load_sounds` and
    `validate_blockstates` -- produced a green run that had silently done nothing (an empty
    `sounds.rs`, and no blockstate check at all).
    """


def repo_root_from_here():
    """`<repo>`, derived from **this file's** location, or `$MC_REPO_ROOT`.

    The previous derivation walked five parents up from `sys.argv[1]`, the extractor's
    *output* directory. That is only correct when the output directory is the canonical
    `crates/mc-data/extractor/out`. Every regenerate into a scratch directory -- which is the
    documented way to diff a change against the committed JSON -- resolved the repo root to
    garbage, which silently disabled the sound table and the blockstate check.

    codegen.py lives at `<repo>/mc-rs/crates/mc-data/extractor/codegen.py`, so the root is
    four parents up from its own directory, and does not move when the caller picks a
    different output path.
    """
    env = os.environ.get("MC_REPO_ROOT")
    if env:
        return os.path.abspath(env)
    here = os.path.dirname(os.path.abspath(__file__))
    # extractor -> mc-data -> crates -> mc-rs -> <repo>
    return os.path.abspath(os.path.join(here, "..", "..", "..", ".."))


# --------------------------------------------------------------------- helpers


def f32(v):
    v = float(v)
    if v != v:
        return "f32::NAN"
    if v == float("inf"):
        return "f32::INFINITY"
    if v == float("-inf"):
        return "f32::NEG_INFINITY"
    return "{}f32".format(repr(v))


def f64(v):
    v = float(v)
    if v != v:
        return "f64::NAN"
    if v == float("inf"):
        return "f64::INFINITY"
    if v == float("-inf"):
        return "f64::NEG_INFINITY"
    return "{}f64".format(repr(v))


def rs(s):
    """A Rust string literal."""
    if s is None:
        return '""'
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def pascal(name):
    """`redstoneLight` / `RED_SANDSTONE` / `Ender Dragon` -> `RedstoneLight` etc."""
    parts = re.split(r"[^0-9A-Za-z]+", name)
    out = []
    for p in parts:
        if not p:
            continue
        if p.isupper() and len(p) > 1:
            out.append(p.capitalize())
        else:
            out.append(p[0].upper() + p[1:])
    ident = "".join(out)
    if not ident:
        ident = "Unknown"
    if ident[0].isdigit():
        ident = "N" + ident
    return ident


def doc(text):
    return "/// {}".format(text.replace("\n", " "))


class Dedup:
    """Interns rendered Rust expressions so identical rows share one table slot."""

    def __init__(self):
        self.index = {}
        self.items = []

    def intern(self, key, render):
        i = self.index.get(key)
        if i is None:
            i = len(self.items)
            self.index[key] = i
            self.items.append(render)
        return i


def write(path, text):
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print("  wrote {} ({} lines)".format(os.path.basename(path), text.count("\n") + 1))


