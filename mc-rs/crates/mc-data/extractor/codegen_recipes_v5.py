#!/usr/bin/env python3
"""Generate mc-data's 1.7.10 crafting recipe table.

    python codegen_recipes_v5.py <recipes_v5.tsv> <mc-data/src/v5>

Input: the dump `V17RecipeDump.java` writes (see `run-v17-recipes.ps1`): the recipe list of the
1.7.10 `CraftingManager` in its runtime order, one line per recipe. The manager's constructor
registers every recipe (java17: `RecipesTools`, `RecipesWeapons`, `RecipesIngots`, `RecipesFood`,
`RecipesCrafting`, `RecipesArmor`, `RecipesDyes`, then its own list) and sorts the list once
(`Collections.sort`: shaped before shapeless, larger before smaller, registration order kept for
ties); `findMatchingRecipe` returns the first match, so the order is part of the table.

Output: `recipe_table.rs` in the given directory: `RECIPES_V5` (one `RecipeV5` per recipe, in
list order) and `MAP_EXTENDING_PATTERN_V5` (the shaped pattern `RecipesMapExtending.matches`
checks first). Ingredient stack sizes are dropped (matching compares item and damage only);
output counts and damages are kept exactly.

Line kinds: `S` shaped, `N` shaped with `ShapedRecipes.func_92100_c` set (the result takes an
ingredient's tag), `L` shapeless, `D` one of the five special recipes, `P` the shaped pattern of
the `D` line before it.
"""

import os
import sys

HEADER = """// @generated by crates/mc-data/extractor/codegen_recipes_v5.py -- DO NOT EDIT.
// Source: the 1.7.10 CraftingManager's recipe list after its constructor (registration, then
// Collections.sort), dumped by extractor/V17RecipeDump.java into extractor/out/recipes_v5.tsv.
// Ingredient stack sizes are dropped: ShapedRecipes and ShapelessRecipes compare item and damage
// only.
"""

# The special recipes 1.7.10 registers (java17: `CraftingManager.<init>`), by class.
DYNAMIC = {
    "net.minecraft.item.crafting.RecipesArmorDyes": "ArmorDyes",
    "net.minecraft.item.crafting.RecipeBookCloning": "BookCloning",
    "net.minecraft.item.crafting.RecipesMapCloning": "MapCloning",
    "net.minecraft.item.crafting.RecipesMapExtending": "MapExtending",
    "net.minecraft.item.crafting.RecipeFireworks": "Fireworks",
}

EXPECTED_COUNT = 317


def ingredient(value):
    if value == "-":
        return "None"
    item, _count, damage = value.split(",")
    return "Some(Ingredient::exact({}, {}))".format(item, damage)


def shapeless_ingredient(value):
    item, _count, damage = value.split(",")
    return "Ingredient::exact({}, {})".format(item, damage)


def stack(value):
    item, count, damage = value.split(",")
    return "RecipeStack::with_damage({}, {}, {})".format(item, count, damage)


def shaped(parts):
    width, height = int(parts[2]), int(parts[3])
    inputs = parts[5:]
    assert len(inputs) == width * height, parts
    return "ShapedRecipe::new({}, {}, &[{}], {})".format(
        width, height, ", ".join(ingredient(v) for v in inputs), stack(parts[4])
    )


def build(lines):
    assert lines[0] == "COUNT\t{}".format(EXPECTED_COUNT), lines[0]
    entries = []
    pattern = None
    kinds = []
    for line in lines[1:]:
        parts = line.split("\t")
        kind = parts[0]
        index = int(parts[1])
        if kind == "P":
            # The pattern of the special recipe on the line before.
            assert kinds and kinds[-1] == "MapExtending" and index == len(entries) - 1, line
            assert pattern is None, "one patterned special recipe"
            pattern = shaped(parts)
            continue
        assert index == len(entries), line
        if kind == "S":
            entries.append("    RecipeV5::Static(StaticRecipe::Shaped({})),".format(shaped(parts)))
            kinds.append("S")
        elif kind == "N":
            entries.append("    RecipeV5::CopiesIngredientTag({}),".format(shaped(parts)))
            kinds.append("N")
        elif kind == "L":
            size = int(parts[2])
            inputs = parts[4:]
            assert len(inputs) == size, line
            entries.append(
                "    RecipeV5::Static(StaticRecipe::Shapeless(ShapelessRecipe::new(&[{}], {}))),".format(
                    ", ".join(shapeless_ingredient(v) for v in inputs), stack(parts[3])
                )
            )
            kinds.append("L")
        elif kind == "D":
            name = DYNAMIC[parts[2]]
            entries.append("    RecipeV5::Dynamic(DynamicRecipeKind::{}),".format(name))
            kinds.append(name)
        else:
            raise AssertionError(line)
    assert len(entries) == EXPECTED_COUNT, len(entries)
    assert sorted(k for k in kinds if k in DYNAMIC.values()) == sorted(DYNAMIC.values()), kinds
    assert kinds.count("N") == 1, "one recipe copies an ingredient's tag (the carrot on a stick)"
    assert pattern is not None, "RecipesMapExtending's pattern"
    return entries, pattern


def render(entries, pattern):
    return (
        HEADER
        + "\n/// The 1.7.10 crafting manager's recipe list, in the order `findMatchingRecipe` tries it.\n"
        + "#[rustfmt::skip]\n"
        + "pub(super) static RECIPES_V5: [RecipeV5; {}] = [\n".format(len(entries))
        + "\n".join(entries)
        + "\n];\n\n"
        + "/// The shaped pattern `RecipesMapExtending` extends: eight paper around a filled map of any\n"
        + "/// damage (java17: `RecipesMapExtending.<init>`).\n"
        + "#[rustfmt::skip]\n"
        + "pub(super) static MAP_EXTENDING_PATTERN_V5: ShapedRecipe = {};\n".format(pattern)
    )


def main():
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    src = os.path.abspath(sys.argv[1])
    dst = os.path.abspath(sys.argv[2])
    with open(src, encoding="utf-8-sig") as fh:
        lines = [line.rstrip("\r\n") for line in fh if line.strip()]
    entries, pattern = build(lines)
    text = render(entries, pattern)
    path = os.path.join(dst, "recipe_table.rs")
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print("  wrote {} ({} recipes)".format(path, len(entries)))


if __name__ == "__main__":
    main()
