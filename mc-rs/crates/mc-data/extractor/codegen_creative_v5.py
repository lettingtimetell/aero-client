#!/usr/bin/env python3
"""Generate mc-data's 1.7.10 creative inventory lists.

    python codegen_creative_v5.py <creative_v5.tsv> <mc-data/src/v5>

Input: the dump `V17CreativeDump.java` writes (see `run-v17-creative.ps1`): for every creative tab
of 1.7.10, in tab order, the stacks `CreativeTabs.displayAllReleventItems` lists, then the pool
the search tab filters (`GuiContainerCreative.updateCreativeSearch`). The client's texture maps
register every block's and item's icons before any creative screen opens, and some sub-item lists
count those icons, so the dumper registers them first, as the client does.

Output: `creative_table.rs` in the given directory: `CREATIVE_TABS_V5` (each tab's label and
list, by tab index) and `CREATIVE_SEARCH_V5` (the search pool), both in the order 1.7.10 shows
them. A stack is a plain item (count 1, no tag) or an enchanted book storing one enchantment; the
dumper refuses anything else.
"""

import os
import sys

HEADER = """// @generated by crates/mc-data/extractor/codegen_creative_v5.py -- DO NOT EDIT.
// Source: the 1.7.10 creative tabs' lists and the search tab's pool, dumped by
// extractor/V17CreativeDump.java into extractor/out/creative_v5.tsv.
"""

TAB_COUNT = 12
PER_LINE = 6


def entry(parts):
    kind = parts[0]
    if kind == "S":
        item, damage = int(parts[1]), int(parts[2])
        assert 0 <= item < 32000 and -32768 <= damage < 32768, parts
        return "item({}, {})".format(item, damage)
    if kind == "B":
        enchantment, level = int(parts[1]), int(parts[2])
        assert 0 <= enchantment < 256 and 0 < level < 256, parts
        return "book({}, {})".format(enchantment, level)
    raise AssertionError(parts)


def build(lines):
    tabs = []
    search = None
    current = None
    for line in lines:
        parts = line.split("\t")
        if parts[0] == "TAB":
            assert search is None, "tabs come first"
            assert int(parts[1]) == len(tabs), line
            current = []
            tabs.append((parts[2], current))
        elif parts[0] == "SEARCH":
            assert search is None, line
            search = []
            current = search
        else:
            assert current is not None, line
            current.append(entry(parts))
    assert len(tabs) == TAB_COUNT, len(tabs)
    assert search, "the search pool"
    labels = [label for label, _ in tabs]
    assert labels[5] == "search" and labels[11] == "inventory", labels
    assert not tabs[5][1] and not tabs[11][1], "the search and inventory tabs list nothing"
    return tabs, search


def rows(entries, indent):
    out = []
    for start in range(0, len(entries), PER_LINE):
        out.append(indent + ", ".join(entries[start:start + PER_LINE]) + ",")
    return "\n".join(out)


def render(tabs, search):
    parts = [HEADER]
    parts.append(
        "\n/// Each 1.7.10 creative tab's label and list, by tab index (java17 "
        "`CreativeTabs.creativeTabArray`).\n"
    )
    parts.append("#[rustfmt::skip]\n")
    parts.append(
        "pub(super) static CREATIVE_TABS_V5: [(&str, &[CreativeStackV5]); {}] = [\n".format(len(tabs))
    )
    for label, entries in tabs:
        if entries:
            parts.append('    ("{}", &[\n{}\n    ]),\n'.format(label, rows(entries, "        ")))
        else:
            parts.append('    ("{}", &[]),\n'.format(label))
    parts.append("];\n\n")
    parts.append(
        "/// The pool the 1.7.10 search tab filters (java17 "
        "`GuiContainerCreative.updateCreativeSearch`).\n"
    )
    parts.append("#[rustfmt::skip]\n")
    parts.append("pub(super) static CREATIVE_SEARCH_V5: [CreativeStackV5; {}] = [\n".format(len(search)))
    parts.append(rows(search, "    ") + "\n];\n")
    return "".join(parts)


def main():
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    src = os.path.abspath(sys.argv[1])
    dst = os.path.abspath(sys.argv[2])
    with open(src, encoding="utf-8-sig") as fh:
        lines = [line.rstrip("\r\n") for line in fh if line.strip()]
    tabs, search = build(lines)
    text = render(tabs, search)
    path = os.path.join(dst, "creative_table.rs")
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print("  wrote {} ({} tab stacks, {} search stacks)".format(
        path, sum(len(entries) for _, entries in tabs), len(search)))


if __name__ == "__main__":
    main()
